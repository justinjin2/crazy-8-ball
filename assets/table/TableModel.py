def check_physics(L, phys, cloth, everything, everything_caps):
    p = L.p
    R, Rr = L.R, L.Rr
    tol = p['physics_tolerance']
    cushion_tags = {T_CUSHION, T_KNOB, T_CUSHION_TOP, T_FACING_WALL}
    cush_bvh, _, _ = bvh_of([cloth], cushion_tags)
    zn = L.nose
    out = {}
    # (a) centres on the physics offset boundary sit exactly R from the drawn nose slice
    seg_dev = {}
    samples = []
    for name, a, b in phys.segments:
        seg = L.segs[name]
        n = tuple(seg['normal'])
        ln = math.dist(a, b)
        k = max(2, int(ln / 0.1))
        worst = 0.0
        for i in range(k + 1):
            c = add(add(a, mul(sub(b, a), i / k)), mul(n, R))
            if not phys.free(c, R):
                continue
            loc, nrm, idx, d = cush_bvh.find_nearest(Vector((c[0], c[1], zn)))
            worst = max(worst, abs(d - R))
            samples.append(c)
        seg_dev[name] = worst
    pt_dev = {}
    for name, c0, r in phys.points:
        worst = 0.0
        for k in range(180):
            a = 2 * pi * k / 180
            c = polar(c0, R + r, a)
            if not phys.free(c, R):
                continue
            loc, nrm, idx, d = cush_bvh.find_nearest(Vector((c[0], c[1], zn)))
            worst = max(worst, abs(d - R))
        pt_dev[name] = worst
    out['a_nose_line'] = max(list(seg_dev.values()) + list(pt_dev.values()))
    out['segments'] = seg_dev
    out['points'] = pt_dev
    # free centres near the cushions and pockets
    step = p['free_grid']
    free_R, free_Rr = [], []
    for x in frange(-L.g['cloth']['half_length'] - 3.0, L.g['cloth']['half_length'] + 3.0, step):
        for y in frange(-L.g['cloth']['half_width'] - 3.0, L.g['cloth']['half_width'] + 3.0, step):
            q = (x, y)
            if abs(x) < 44 and abs(y) < 19:
                continue
            if not phys.near_band(q, p['free_band']) or not phys.in_region(q) or phys.captured(q):
                continue
            cl = phys.clearance(q)
            if cl >= R:
                free_R.append(q)
            if cl >= Rr:
                free_Rr.append(q)
    free_R += samples
    # (b) free centres are at least R - tol from the drawn slice
    worst_b = 1e9
    for c in free_R:
        loc, nrm, idx, d = cush_bvh.find_nearest(Vector((c[0], c[1], zn)))
        if d is not None:
            worst_b = min(worst_b, d)
    out['b_ball_envelope_min'] = worst_b
    # (c) no rubber in front of the nose line at any height: 2D, every cushion vertex
    verts = sorted(set(i for pl in cloth.select(cushion_tags) for i in pl))
    kd = KDTree(len(verts))
    for k, i in enumerate(verts):
        q = cloth.co[i]
        kd.insert((q[0], q[1], 0.0), k)
    kd.balance()
    worst_c = 1e9
    for c in free_R:
        co, idx, d = kd.find((c[0], c[1], 0.0))
        worst_c = min(worst_c, d)
    out['c_rubber_min'] = worst_c
    # (d) 3D sphere clearance
    worst_d = {}
    for label, (bvh, _, _) in (('no_caps', everything), ('caps', everything_caps)):
        worst = 1e9
        for c in free_R:
            loc, nrm, idx, d = bvh.find_nearest(Vector((c[0], c[1], R)))
            if d is not None:
                worst = min(worst, d - R)
        for c in free_Rr:
            loc, nrm, idx, d = bvh.find_nearest(Vector((c[0], c[1], Rr)))
            if d is not None:
                worst = min(worst, d - Rr)
        worst_d[label] = worst
    out['d_free_min_gap'] = min(worst_d.values())
    out['d_free_detail'] = worst_d
    out['free_centres'] = {'physics_radius': len(free_R), 'render_radius': len(free_Rr)}
    return out, free_R


def check_falling(L, phys, liners_excluded, liners_excluded_caps):
    """(d) Falling and tipping drawn balls clear everything but the cloth lip and the cup liner."""
    p = L.p
    R, Rr = L.R, L.Rr
    worst = {'no_caps': 1e9, 'caps': 1e9}
    where = {}
    count = 0
    for pk in L.pockets.values():
        jaws = (pk.endA.J, pk.endB.J)
        centres = []
        rmax = pk.r - R
        for rad in frange(0.0, rmax, p['fall_grid']) + [rmax]:
            nang = max(1, int(2 * pi * rad / p['fall_grid']))
            for k in range(nang):
                a = 2 * pi * k / nang
                centres.append(polar(pk.H, rad, a))
        for zc in frange(p['fall_depth'] + Rr, Rr - R, 0.2) + [Rr - R]:
            for c in centres:
                if zc > -1.0 and min(math.dist(c, j) for j in jaws) < Rr + L.jaw_r:
                    continue
                count += 1
                for label, (bvh, _, tg) in (('no_caps', liners_excluded), ('caps', liners_excluded_caps)):
                    loc, nrm, idx, d = bvh.find_nearest(Vector((c[0], c[1], zc)), Rr)
                    if d is not None and d - Rr < worst[label]:
                        worst[label] = d - Rr
                        where[label] = (pk.id, round(c[0], 3), round(c[1], 3), round(zc, 3), tg[idx],
                                        [round(x, 3) for x in loc])
        # the tip: pivot on the mouth rim, centre swinging in and down
        a0 = ang(sub(pk.endA.J, pk.H))
        span = L.mouth_span(pk, a0, ang(sub(pk.endB.J, pk.H)))
        for k in range(61):
            piv = polar(pk.H, pk.r, a0 + span * k / 60)
            if phys.clearance(piv) < Rr:
                continue  # the drawn ball cannot start its tip there
            inward = unit(sub(pk.H, piv))
            for tdeg in range(0, 91, 10):
                th = radians(tdeg)
                c = add(piv, mul(inward, R * sin(th)))
                zc = Rr + R * (cos(th) - 1)
                if phys.clearance(c) < Rr:
                    continue  # a drawn-size ball there would already overlap the cushion (1.08x)
                count += 1
                for label, (bvh, _, tg) in (('no_caps', liners_excluded), ('caps', liners_excluded_caps)):
                    loc, nrm, idx, d = bvh.find_nearest(Vector((c[0], c[1], zc)), Rr)
                    if d is not None and d - Rr < worst[label]:
                        worst[label] = d - Rr
                        where[label] = ('tip', pk.id, round(c[0], 3), round(c[1], 3), round(zc, 3), tg[idx],
                                        [round(x, 3) for x in loc])
    return {'min_gap': min(worst.values()), 'detail': worst, 'where': where, 'centres': count}


def check_holes(L, cloth, pockets):
    """(e) circle fit of the roll where it turns vertical; cup clearance and depth."""
    p = L.p
    rho = p['roll_radius']
    out = []
    worst = 0.0
    ring = {}
    for pl, t in zip(cloth.polys, cloth.tags):
        if t != T_ROLL:
            continue
        for i in pl:
            q = cloth.co[i]
            if abs(q[2] + rho) < 1e-4:
                ring[i] = q
    for hid in sorted(L.pockets):
        pk = L.pockets[hid]
        pts = [q for q in ring.values() if abs(math.dist(q[:2], pk.H) - pk.r) < 0.02]
        centre, r = fit_circle([q[:2] for q in pts])
        dev = max(math.dist(centre, pk.H), abs(r - pk.r))
        mid_a = ang(mul(pk.H, -1))
        ds = sorted(pts, key=lambda q: (ang(sub(q[:2], pk.H)) - mid_a + pi) % (2 * pi))
        rim = [math.dist(q[:2], pk.H) for q in ds]
        mids = [math.dist(mul(add(a[:2], b[:2]), 0.5), pk.H) for a, b in zip(ds, ds[1:])]
        rim_min, rim_max = min(rim + mids), max(rim + mids)
        worst = max(worst, dev, abs(rim_min - pk.r), abs(rim_max - pk.r))
        cup = [pockets.co[i] for pl, t in zip(pockets.polys, pockets.tags) if t == T_CUP for i in pl]
        cup = [q for q in cup if math.dist(q[:2], pk.H) < pk.clear + 0.1]
        rv = L.cup_radius_vertex(pk)
        clear_min = min(rv * cos(pi / p['cup_segments']), min(math.dist(q[:2], pk.H) for q in cup))
        depth = -min(q[2] for q in cup)
        out.append({'id': hid, 'x': pk.H[0], 'y': pk.H[1], 'fit_centre': list(centre), 'fit_radius': r,
                    'rim_min': rim_min, 'rim_max': rim_max, 'clear_min': clear_min, 'depth': depth,
                    'ring_vertices': len(pts)})
        assert clear_min >= pk.clear - 1e-9, ('cup inside the clear radius', hid, clear_min)
    return out, worst


def check_cloth_rays(L, phys, cloth):
    """(f) downward rays on a grid: flat cloth everywhere outside the rims, none inside radius - 0.01."""
    p = L.p
    bvh, _, polys = bvh_of([cloth])
    bad_out, bad_in, n_out, n_in = 0, 0, 0, 0
    first = []
    hl, hw = L.g['cloth']['half_length'], L.g['cloth']['half_width']
    step = p['ray_grid']
    down = Vector((0, 0, -1))
    jaws = [pt for _, pt, r in phys.points if r > 0]
    for x in frange(-hl - 3, hl + 3, step):
        for y in frange(-hw - 3, hw + 3, step):
            q = (x, y)
            inside_hole = any(math.dist(q, c) < r - 0.01 for _, c, r in phys.holes)
            outside_rims = all(math.dist(q, c) > r + 0.07 + 1e-6 for _, c, r in phys.holes)
            if not inside_hole:
                if not (outside_rims and phys.in_region(q) and phys.clearance(q) > 0.005):
                    continue
                if min(math.dist(q, j) for j in jaws) < 1.0 and phys.clearance(q) < 0.15:
                    continue  # the concave fillet beside each jaw (the ball never reaches it)
                if abs(x) < hl - 2 and abs(y) < hw - 2 and (round(x / step) % 5 or round(y / step) % 5):
                    continue  # the open middle is one flat face; sample it every 0.5 in
            loc, nrm, idx, d = bvh.ray_cast(Vector((x, y, 5.0)), down)
            if inside_hole:
                n_in += 1
                if loc is not None and abs(loc.z) < 1e-4 and nrm.z > 0.99:
                    bad_in += 1
                    if len(first) < 5:
                        first.append(('flat inside hole', x, y))
            else:
                n_out += 1
                if loc is None or abs(loc.z) > 1e-4 or nrm.z < 0.99:
                    bad_out += 1
                    if len(first) < 5:
                        first.append(('not cloth', x, y, None if loc is None else round(loc.z, 4)))
    return {'rays_outside_rims': n_out, 'bad_outside': bad_out, 'rays_inside_holes': n_in, 'bad_inside': bad_in,
            'first_failures': first}


def check_sights(L, rails):
    groups = []
    for pl, t in zip(rails.polys, rails.tags):
        if t != T_SIGHT:
            continue
        c = [sum(rails.co[i][j] for i in pl) / 3 for j in range(3)]
        for gr in groups:
            if math.dist(gr[0][:2], c[:2]) < 1.0:
                gr.append(c)
                break
        else:
            groups.append([c])
    # centroid of each diamond = mean of its vertices
    verts = {}
    for pl, t in zip(rails.polys, rails.tags):
        if t == T_SIGHT:
            for i in pl:
                verts[i] = rails.co[i]
    centres = []
    for gr in groups:
        pts = [q for q in verts.values() if math.dist(q[:2], gr[0][:2]) < 1.0]
        centres.append((sum(q[0] for q in pts) / len(pts), sum(q[1] for q in pts) / len(pts),
                        sum(q[2] for q in pts) / len(pts)))
    want = []
    for piece in RAIL_PIECES:
        want += [c for c, _ in sight_positions(L, piece[0])]
    worst = 0.0
    for w in want:
        d = min(math.dist(w, c[:2]) for c in centres)
        worst = max(worst, d)
    flush = max(abs(c[2] - L.top) for c in centres)
    return {'count': len(centres), 'max_position_error': worst, 'max_height_error': flush}


