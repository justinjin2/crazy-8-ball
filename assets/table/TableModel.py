def v3(a):
    return (a[0], a[1], a[2])


def vadd(a, b):
    return (a[0] + b[0], a[1] + b[1], a[2] + b[2])


def vmul(a, k):
    return (a[0] * k, a[1] * k, a[2] * k)


def vcross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def vunit(a):
    n = math.sqrt(a[0] ** 2 + a[1] ** 2 + a[2] ** 2)
    return (a[0] / n, a[1] / n, a[2] / n)


def bolt_sites(L):
    """(centre on the leg face, outward normal, across) for every bolt: two per outer leg face."""
    p = L.p
    z_top, _, _, z_floor = leg_levels(L)
    zb = z_top - p['bolt_below_top']
    m = (p['leg_top'] - p['leg_bottom']) / 2 / (z_top - z_floor)  # half-size change per inch of height
    out = []
    for corner in CORNERS:
        sx, sy = corner
        a = leg_half(L, zb)
        f = a / (p['leg_top'] / 2)
        c1, k = p['leg_chamfer'] * f, p['leg_clip'] * f
        cx = sx * (L.X0 - p['skirt_inset'] - p['leg_top'] / 2)
        cy = sy * (L.Y0 - p['skirt_inset'] - p['leg_top'] / 2)
        centre_v = ((-a + c1) + (a - k)) / 2  # middle of the outer face between its chamfers
        # face normal to +x (sx) face: x = cx + sx a(z); a grows with z at rate m
        for axis in ('x', 'y'):
            if axis == 'x':
                n = vunit((sx, 0.0, -m))
                across = (0.0, 1.0, 0.0)
                base = (cx + sx * a, cy + sy * centre_v, zb)
            else:
                n = vunit((0.0, sy, -m))
                across = (1.0, 0.0, 0.0)
                base = (cx + sx * centre_v, cy + sy * a, zb)
            for off in (-p['bolt_spacing'] / 2, p['bolt_spacing'] / 2):
                out.append((vadd(base, vmul(across, off)), n, across))
    return out


def build_hardware(L):
    p = L.p
    kp = p['parts_px_per_stud'] / p['atlas_px'] * L.s
    parts = []
    nseg = p['bolt_segments']
    r0 = p['bolt_diameter'] / 2
    tv0, _ = PARTS_V['chrome']
    for centre, n, across in bolt_sites(L):
        part = Part('Bolt', closed=True)
        e1 = across
        e2 = vunit(vcross(n, e1))
        rings = [(-0.01, r0), (p['bolt_proud'] * 0.6, r0 * 0.9)]
        ids = []
        for off, rad in rings:
            ring = []
            for k in range(nseg):
                a = 2 * pi * k / nseg
                q = vadd(centre, vadd(vmul(n, off), vadd(vmul(e1, rad * cos(a)), vmul(e2, rad * sin(a)))))
                ring.append(part.vk(q))
            ids.append(ring)
        apex = part.vk(vadd(centre, vmul(n, p['bolt_proud'])))

        def buv(i):
            q = part.co[i]
            d = (q[0] - centre[0], q[1] - centre[1], q[2] - centre[2])
            return (0.62 + sum(x * y for x, y in zip(d, e1)) * kp, tv0 + 0.05 + sum(x * y for x, y in zip(d, e2)) * kp)
        for k in range(nseg):
            k2 = (k + 1) % nseg
            quad = [ids[0][k], ids[0][k2], ids[1][k2], ids[1][k]]
            # side: grain-free chrome, u round the bolt, v up its side
            part.quad(*quad, [(0.62 + k / nseg * 0.05, tv0 + 0.01), (0.62 + (k + 1) / nseg * 0.05, tv0 + 0.01),
                              (0.62 + (k + 1) / nseg * 0.05, tv0 + 0.015), (0.62 + k / nseg * 0.05, tv0 + 0.015)],
                      T_BOLT)
            tri = [ids[1][k], ids[1][k2], apex]
            part.f(tri, [buv(i) for i in tri], T_BOLT)
        base = list(reversed(ids[0]))
        part.f(base, plane_uv([part.co[i] for i in base], tuple(-c for c in n), kp, (0.7, tv0 + 0.05)), T_BOLT_HIDDEN)
        parts.append(part)
    return parts


def build_logo(L):
    p = L.p
    part = Part('LogoPlate', closed=True)
    X = L.X0 - p['skirt_inset']
    top_s = p['rail_bottom']
    bot = top_s - p['skirt_height']
    zc = ((top_s - p['skirt_top_chamfer']) + (bot + 0.3)) / 2
    w, hgt = p['logo_size']
    c = p['logo_chamfer']
    xb, xf = X - p['logo_embed'], X + p['logo_proud']

    def rect(x, hw, hh):
        return [part.vk((x, -hw, zc - hh)), part.vk((x, hw, zc - hh)), part.vk((x, hw, zc + hh)),
                part.vk((x, -hw, zc + hh))]
    back = rect(xb, w / 2, hgt / 2)
    mid = rect(xf - c, w / 2, hgt / 2)
    front = rect(xf, w / 2 - c, hgt / 2 - c)
    fw, fh = w - 2 * c, hgt - 2 * c
    # front: UV 0..1 over the face; seen from +x, +y is to the left... u runs with +y? u must turn
    # counterclockwise with the +x normal: basis (y, z) has y x z = +x.
    part.f(front, [((part.co[i][1] + fw / 2) / fw, (part.co[i][2] - zc + fh / 2) / fh) for i in front], T_LOGO_FRONT)
    centre = ((xb + xf) / 2, 0.0, zc)
    faces = [list(reversed(back))]
    for ring_a, ring_b in ((back, mid), (mid, front)):
        for k in range(4):
            k2 = (k + 1) % 4
            faces.append([ring_a[k], ring_a[k2], ring_b[k2], ring_b[k]])
    for quad in faces:
        pts = [part.co[i] for i in quad]
        n = vunit(vcross(tuple(b - a for a, b in zip(pts[0], pts[1])), tuple(b - a for a, b in zip(pts[0], pts[2]))))
        fc = tuple(sum(q[j] for q in pts) / 4 for j in range(3))
        if sum((fc[j] - centre[j]) * n[j] for j in range(3)) < 0:
            quad, pts, n = list(reversed(quad)), list(reversed(pts)), tuple(-c for c in n)
        # the back and the edges map into a tiny patch at the texture's corner
        part.f(quad, plane_uv(pts, n, 0.002, (0.002, 0.002)), T_LOGO_OTHER)
    return [part]


MARKS_UV = {'sticker': (0.0, 0.875, 0.125, 1.0), 'rack': (0.125, 0.625, 0.5, 1.0), 'streak': (0.5, 0.9375, 1.0, 1.0),
            'chalk0': (0.5, 0.8125, 0.625, 0.9375), 'chalk1': (0.625, 0.8125, 0.75, 0.9375),
            'chalk2': (0.75, 0.8125, 0.875, 0.9375), 'chalk3': (0.875, 0.8125, 1.0, 0.9375),
            'toe': (0.0, 0.0, 1.0, 0.0625), 'rim': (0.0, 0.0625, 1.0, 0.125)}


def build_marks(L):
    p = L.p
    part = Part('Marks')
    z = p['marks_lift_studs'] / L.s

    def quad(corners, region):
        """corners CCW from above: (-u, -v), (+u, -v), (+u, +v), (-u, +v) of the region."""
        u0, v0, u1, v1 = MARKS_UV[region]
        ids = [part.v((q[0], q[1], z)) for q in corners]
        part.f(ids, [(u0, v0), (u1, v0), (u1, v1), (u0, v1)], T_MARK)

    def box(c, hx, hy, region):
        quad([(c[0] - hx, c[1] - hy), (c[0] + hx, c[1] - hy), (c[0] + hx, c[1] + hy), (c[0] - hx, c[1] + hy)], region)
    foot = tuple(L.g['spots']['foot'])
    head = tuple(L.g['spots']['head'])
    box(foot, p['sticker_size'] / 2, p['sticker_size'] / 2, 'sticker')
    xs = [b['x'] for b in L.g['rack']['balls']]
    ys = [b['y'] for b in L.g['rack']['balls']]
    m = p['rack_margin']
    quad([(min(xs) - m, min(ys) - m), (max(xs) + m, min(ys) - m), (max(xs) + m, max(ys) + m),
          (min(xs) - m, max(ys) + m)], 'rack')
    apex = tuple(L.g['rack']['apex'])
    hw = p['streak_width'] / 2
    x0 = head[0] - p['streak_back']
    quad([(x0, -hw), (apex[0] - L.R, -hw), (apex[0] - L.R, hw), (x0, hw)], 'streak')
    for k, hid in enumerate(sorted(L.pockets)):
        pk = L.pockets[hid]
        toward = unit(mul(pk.H, -1)) if pk.kind == 'side' else unit(mul(pk.axis, -1))
        c = add(pk.H, mul(toward, pk.r + p['chalk_from_rim']))
        a = ang(toward)
        s2 = p['chalk_size'] / 2
        corners = [add(c, (s2 * (cos(a) * dx - sin(a) * dy), s2 * (sin(a) * dx + cos(a) * dy)))
                   for dx, dy in ((-1, -1), (1, -1), (1, 1), (-1, 1))]
        quad(corners, 'chalk%d' % (k % 4))
    # darkening strips along the cushion toes (rail runs only; the facings are too close to the holes)
    for c in L.cushions:
        rail = L.segs[c['rail']]
        a_, b_ = tuple(rail['a']), tuple(rail['b'])
        n = tuple(rail['normal'])
        d = unit(sub(b_, a_))
        back, front = -p['toe_strip_hidden'], p['toe_strip_width'] - p['toe_strip_hidden']
        pts = [add(a_, mul(n, back)), add(b_, mul(n, back)), add(b_, mul(n, front)), add(a_, mul(n, front))]
        if cross(sub(pts[1], pts[0]), sub(pts[2], pts[0])) < 0:
            pts = [pts[1], pts[0], pts[3], pts[2]]
        quad(pts, 'toe')
    # darkening rings round the rims, over the mouth only
    u0, v0, u1, v1 = MARKS_UV['rim']
    for pk, a0, span, n, xa, xb in L.mouths:
        r_in = pk.r + p['roll_radius']
        r_out = r_in + p['rim_ring_width']
        steps = max(4, arc_steps(r_out, span, p['chord_tol'] * 5))
        inner = [part.v(polar(pk.H, r_in, a0 + span * j / steps) + (z,)) for j in range(steps + 1)]
        outer = [part.v(polar(pk.H, r_out, a0 + span * j / steps) + (z,)) for j in range(steps + 1)]
        for j in range(steps):
            ua, ub = u0 + (u1 - u0) * j / steps, u0 + (u1 - u0) * (j + 1) / steps
            quad_ids = [inner[j], inner[j + 1], outer[j + 1], outer[j]]
            uvs = [(ua, v0), (ub, v0), (ub, v1), (ua, v1)]
            pts = [part.co[i] for i in quad_ids]
            if cross(sub(pts[1][:2], pts[0][:2]), sub(pts[2][:2], pts[0][:2])) < 0:
                quad_ids, uvs = list(reversed(quad_ids)), list(reversed(uvs))
            if cross(sub(uvs[1], uvs[0]), sub(uvs[2], uvs[0])) < 0:
                uvs = [(u0 + u1 - uu, vv) for uu, vv in uvs]  # mirror u so the texture is not mirrored
            part.f(quad_ids, uvs, T_MARK)
    return [part]


