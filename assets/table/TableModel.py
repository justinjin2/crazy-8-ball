PARTS_V = {'leather': (0.0, 0.25), 'cup': (0.30, 0.66), 'floor': (0.30, 0.56), 'chrome': (0.70, 0.80),
           'chrome_under': (0.82, 0.88), 'rubber': (0.90, 0.96)}


def pocket_frame(L, pk):
    """Angles about the opening centre for the rim, roll and wall, shared by Pockets and Caps."""
    p = L.p
    rt = pk.Rc + p['rim_roll']
    ro = pk.Rc + pk.w
    pk.EA, pk.EB = L.back_cross(pk, pk.endA, rt), L.back_cross(pk, pk.endB, rt)
    pk.FA, pk.FB = L.back_cross(pk, pk.endA, ro), L.back_cross(pk, pk.endB, ro)
    # The roll and the wall run from heel to heel (the opening circle passes through both), or
    # from where the roll's top edge meets the back line when that comes later (side pockets), so
    # no leather lies over a cushion.
    a_pa, a_pb = ang(sub(pk.endA.P, pk.Hp)), ang(sub(pk.endB.P, pk.Hp))
    full = L.far_span(pk, a_pa, a_pb)
    sg = math.copysign(1, full)

    def along(a):
        return ((a - a_pa) * sg) % (2 * pi)
    a_ea, a_eb = ang(sub(pk.EA, pk.Hp)), ang(sub(pk.EB, pk.Hp))
    start = a_ea if along(a_ea) < pi else a_pa
    finish = a_eb if along(a_eb) < abs(full) else a_pb
    pk.psiA = start
    pk.span = L.far_span(pk, start, finish)
    n0 = arc_steps(pk.Rc, pk.span, p['chord_tol'])
    ts = {0.0: False, 1.0: False}  # the cup's 32 sides already keep the chord error under chord_tol
    for phi in L.cup_vertex_angles(pk):
        q = tc.ray_circle(pk.H, (cos(phi), sin(phi)), pk.Hp, pk.Rc)
        t = ((ang(sub(q, pk.Hp)) - pk.psiA) * math.copysign(1, pk.span)) % (2 * pi) / abs(pk.span)
        if 1e-4 < t < 1 - 1e-4:
            for key in list(ts):
                if abs(key - t) < 0.2 / n0 and not ts[key] and key not in (0.0, 1.0):
                    del ts[key]
            ts[round(t, 9)] = True
    pk.ts = sorted(ts)


def fin(part, pts, normal2, thickness, tag, kp, origin):
    """A thin closed plate through the planar polygon pts (vertical plane with horizontal unit
    normal normal2): seen from both sides, with no slot a ray could slip through."""
    n3 = (normal2[0], normal2[1], 0.0)
    h = thickness / 2
    front = [part.v((q[0] + normal2[0] * h, q[1] + normal2[1] * h, q[2])) for q in pts]
    back = [part.v((q[0] - normal2[0] * h, q[1] - normal2[1] * h, q[2])) for q in pts]
    nb = (-n3[0], -n3[1], 0.0)
    # fan from vertex 0 (the polygon is star-shaped about it), so no concave quad gets split badly
    for ring, want in ((front, 1.0), (back, -1.0)):
        for j in range(1, len(ring) - 1):
            tri = [ring[0], ring[j], ring[j + 1]]
            k = len(part.faces)
            part.f(tri, plane_uv([part.co[i] for i in tri], n3 if want > 0 else nb, kp, origin), tag)
            if dot(part.face_normal(k)[:2], normal2) * want < 0:
                part.flip(k)
            part.fix_uv_sign(k)
    m = len(pts)
    for i in range(m):
        i2 = (i + 1) % m
        quad = [front[i], back[i], back[i2], front[i2]]
        q3 = [part.co[j] for j in quad]
        e = sub(pts[i2][:2], pts[i][:2])
        ez = pts[i2][2] - pts[i][2]
        # outward: perpendicular to the edge within the fin plane, away from the centroid
        c = [sum(q[j] for q in pts) / m for j in range(3)]
        mid = [(pts[i][j] + pts[i2][j]) / 2 for j in range(3)]
        away = tuple(mid[j] - c[j] for j in range(3))
        out = vunit(vcross((e[0], e[1], ez), n3))  # the side face's own normal ...
        if sum(out[j] * away[j] for j in range(3)) < 0:  # ... pointing out of the plate
            out = tuple(-x for x in out)
        k = len(part.faces)
        part.f(quad, plane_uv(q3, out, kp, origin), tag)
        nrm = part.face_normal(k)
        if sum(nrm[j] * out[j] for j in range(3)) < 0:
            part.flip(k)
        part.fix_uv_sign(k)


def build_pocket(L, part, pk):
    p = L.p
    kp = p['parts_px_per_stud'] / p['atlas_px'] * L.s
    rr = p['rim_roll']
    top = L.top
    n_roll = arc_steps(rr, pi / 2, p['chord_tol'])
    lv0, _ = PARTS_V['leather']
    psis = [pk.psiA + pk.span * t for t in pk.ts]
    u_of = [0.5 + (psi - pk.psiA) * pk.Rc * kp for psi in psis]
    # Roll profile (radius about Hp, z): from the rim onto the opening edge
    prof = []
    for j in range(n_roll + 1):
        beta = pi / 2 * j / n_roll
        prof.append((pk.Rc + rr - rr * sin(beta), top - rr + rr * cos(beta)))
    pv = [pk.w - rr]
    for a, b in zip(prof, prof[1:]):
        pv.append(pv[-1] + math.dist(a, b))
    cols = []
    for psi in psis:
        dirn = (cos(psi), sin(psi))
        col = [part.vk(add(pk.Hp, mul(dirn, rad)) + (z,)) for rad, z in prof]
        topq = add(pk.Hp, mul(dirn, pk.Rc))
        phi = ang(sub(topq, pk.H))
        bot = L.cup_point(pk, phi)
        col.append(part.vk(bot + (0.0,)))
        cols.append(col)
    start = len(part.faces)
    for j in range(len(psis) - 1):
        for m in range(len(prof)):
            a, b = cols[j][m], cols[j + 1][m]
            c_, d = cols[j + 1][m + 1], cols[j][m + 1]
            if m < len(prof) - 1:
                va, vb = pv[m], pv[m + 1]
                tag = T_RIM
            else:
                qa, qb = part.co[cols[j][m]], part.co[cols[j][m + 1]]
                va, vb = pv[-1], pv[-1] + math.dist(qa, qb)
                tag = T_WALL
            part.quad(a, b, c_, d, [(u_of[j], lv0 + va * kp), (u_of[j + 1], lv0 + va * kp),
                                    (u_of[j + 1], lv0 + vb * kp), (u_of[j], lv0 + vb * kp)], tag)
    # the wall faces the pocket axis
    mid = len(psis) // 2
    ref = start + mid * (len(prof)) + len(prof) - 1
    wall_n = part.face_normal(ref)
    if dot(wall_n[:2], (cos(psis[mid]), sin(psis[mid]))) > 0:
        part.flip(start)
    # Flat leather rim: roll top edge, back line, rim outer arc, back line
    ro = pk.Rc + pk.w
    outer = [q for q, _ in reversed(rim_outer(L, pk))]
    inner = [part.co[c[0]][:2] for c in cols]
    inner_ids = [c[0] for c in cols]

    def depth(end, q):
        return dot(sub(q, end.ra), end.orr)

    def clip_front(pts, ids, end):
        """Drop leading roll-top points in front of this end's back line (over the cushion);
        start on the back line instead. Without any, start at the heel."""
        k = 0
        while depth(end, pts[k]) < L.W - 1e-9:
            k += 1
        if k == 0:
            return [end.P] + pts, [part.vk(end.P + (top,))] + ids, None
        a, b = pts[k - 1], pts[k]
        t = (L.W - depth(end, a)) / (depth(end, b) - depth(end, a))
        x = add(a, mul(sub(b, a), t))
        return [x] + pts[k:], [part.vk(x + (top,))] + ids[k:], x
    inner, inner_ids, xa = clip_front(inner, inner_ids, pk.endA)
    rin, rids, xb = clip_front(list(reversed(inner)), list(reversed(inner_ids)), pk.endB)
    inner, inner_ids = list(reversed(rin)), list(reversed(rids))
    # Close each roll end (a quarter-round wedge between the flush rim and the wall top), and on
    # the side pockets the sliver of rail top between the heel and where the rim meets the back line.
    for which, col, x in ((0, cols[0], xa), (1, cols[-1], xb)):
        end = pk.endA if which == 0 else pk.endB
        heel_top = part.vk(end.P + (top,))
        radial = unit(sub(end.P, pk.Hp))
        tang = (-radial[1], radial[0])
        want = mul(tang, math.copysign(1, pk.span) if which == 0 else -math.copysign(1, pk.span))
        fan_pts = [part.co[heel_top]] + [part.co[col[m]] for m in range(len(prof))]
        fin(part, fan_pts, want, 0.004, T_RIM, kp, (0.55, lv0 + 0.15))  # seen from the pocket and the heel
        # the 0.02 step from the cushion top up to the flush rim, between the rail and the heel
        fq = pk.FA if which == 0 else pk.FB
        strip = [part.v(fq + (L.cushion_top - 0.005,)), part.v(end.P + (L.cushion_top - 0.005,)),
                 part.v(end.P + (top,)), part.v(fq + (top,))]
        pts = [part.co[i] for i in strip]
        k = len(part.faces)
        nrm = end.nr
        part.f(strip, plane_uv(pts, (nrm[0], nrm[1], 0.0), kp, (0.6, lv0 + 0.2)), T_RIM)
        if dot(part.face_normal(k)[:2], nrm) < 0:
            part.flip(k)
        part.fix_uv_sign(k)
        if x is not None:
            tri = [heel_top, col[0], part.vk(x + (top,))]
            pts = [part.co[i] for i in tri]
            k = len(part.faces)
            part.f(tri, plane_uv(pts, (0.0, 0.0, 1.0), kp, (0.55, lv0 + 0.18)), T_RIM)
            if part.face_normal(k)[2] < 0:
                part.flip(k)
            part.fix_uv_sign(k)
    loop = inner + outer
    verts, tris = tc.triangulate(loop)
    ids = inner_ids + [part.vk(q + (top,)) for q in outer]
    start = len(part.faces)
    for tri in tris:
        uvs = []
        for i in tri:
            q = verts[i]
            psi = ang(sub(q, pk.Hp))
            dpsi = ((psi - pk.psiA + pi) % (2 * pi)) - pi
            if pk.span > 0 and dpsi < -pi / 2:
                dpsi += 2 * pi
            if pk.span < 0 and dpsi > pi / 2:
                dpsi -= 2 * pi
            uvs.append((0.5 + dpsi * pk.Rc * kp, lv0 + (ro - math.dist(q, pk.Hp)) * kp))
        part.f([ids[i] for i in tri], uvs, T_RIM)
    # Close the wall ends: from the heel column down to the cup rim. The side pockets' heels
    # stand in the open throat, so each end is a thin two-sided fin (0.001 in apart).
    for which, col in ((0, cols[0]), (1, cols[-1])):
        heel = pk.endA.P if which == 0 else pk.endB.P
        corners = [part.co[col[-2]], part.co[col[-1]], heel + (L.levels[0][1],)]
        radial = unit(sub(heel, pk.H))
        fin(part, corners, (-radial[1], radial[0]), 0.004, T_WALL, kp, (0.5, lv0 + 0.15))
    # Cup: single-sided, normals inward, flat floor
    cv0, cv1 = PARTS_V['cup']
    n = p['cup_segments']
    rv = L.cup_radius_vertex(pk)
    angles = L.cup_vertex_angles(pk)
    depth = -p['cup_depth']
    ring0 = [part.vk(polar(pk.H, rv, a) + (0.0,)) for a in angles]
    ring1 = [part.vk(polar(pk.H, rv, a) + (depth,)) for a in angles]
    circ = 2 * pi * pk.cup_r * kp
    start = len(part.faces)
    for k in range(n):
        k2 = (k + 1) % n
        u0, u1 = 0.02 + circ * k / n, 0.02 + circ * (k + 1) / n
        part.quad(ring0[k], ring0[k2], ring1[k2], ring1[k],
                  [(u0, cv0), (u1, cv0), (u1, cv0 - depth * kp), (u0, cv0 - depth * kp)], T_CUP)
    if dot(part.face_normal(start)[:2], (cos(angles[0] + pi / n), sin(angles[0] + pi / n))) > 0:
        part.flip(start)
    f0, _ = PARTS_V['floor']
    ids = list(ring1)
    uvs = [(0.72 + (polar(pk.H, rv, a)[0] - pk.H[0] + 3) * kp, f0 + (polar(pk.H, rv, a)[1] - pk.H[1] + 3) * kp)
           for a in angles]
    start = len(part.faces)
    part.f(ids, uvs, T_CUP_FLOOR)
    if part.face_normal(start)[2] < 0:
        part.flip(start)


def build_pockets(L):
    part = Part('Pockets')
    for hid in sorted(L.pockets):
        pk = L.pockets[hid]
        pocket_frame(L, pk)
        build_pocket(L, part, pk)
    return [part]


