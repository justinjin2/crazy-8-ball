def check_uvs(L, data):
    p = L.p
    s = L.s
    px = p['atlas_px']
    target = {'cloth': px / (p['cloth_studs_per_repeat']), 'rails': p['rails_px_per_stud'],
              'body': p['body_px_per_stud'], 'parts_min': 250.0}
    stats = {}
    ok = True
    mirrored_total = 0
    for name, md in data.items():
        mirrored = 0
        dens = {}
        bad_tags = {}
        tag_dens = {}
        grain_at = None
        grain_worst = 1.0
        for k, (pl, lp, t) in enumerate(zip(md.polys, md.loops, md.tags)):
            pts = [md.co[i] for i in pl]
            uvs = [md.uv[i] for i in lp]
            area, cr = tri_area3(*pts)
            tan, uv_area = uv_tangent(pts, uvs)
            if uv_area <= 0:
                mirrored += 1
                bad_tags[t] = bad_tags.get(t, 0) + 1
            if area * s * s < 1e-10:
                continue
            density = math.sqrt(abs(uv_area) / (area * s * s)) * px
            lo_, hi_ = tag_dens.get(t, (1e9, 0.0))
            tag_dens[t] = (min(lo_, density), max(hi_, density))
            for tags, kind, tolkey in UV_RULES.get(name, []):
                if t in tags:
                    key = kind + ('' if tolkey is None else ':' + tolkey)
                    lo, hi = dens.get(key, (1e9, 0.0))
                    dens[key] = (min(lo, density), max(hi, density))
            # wood grain
            n = vunit(cr)
            expect = None
            if False:
                pass
            elif name == 'Rails' and t == T_RAIL_FLAT:
                c = [sum(q[j] for q in pts) / 3 for j in range(3)]
                expect = (1.0, 0.0, 0.0) if abs(c[1]) - L.g['cloth']['half_width'] > abs(c[0]) - L.g['cloth']['half_length'] \
                    else (0.0, 1.0, 0.0)
            if name == 'Rails' and t in (T_RAIL_FLAT, T_RAIL_BULL, T_RAIL_OUTER) and \
                    min(abs(sum(q[0] for q in pts) / 3), abs(sum(q[1] for q in pts) / 3)) < 1.0:
                # seam chamfer: the grain is the piece axis, seen in the tilted face
                c = [sum(q[j] for q in pts) / 3 for j in range(3)]
                ax = (1.0, 0.0, 0.0) if abs(c[0]) < 1.0 else (0.0, 1.0, 0.0)
                dn = sum(a * b for a, b in zip(ax, n))
                expect = vunit(tuple(a - dn * b for a, b in zip(ax, n)))
            elif (name == 'Rails' and t in (T_RAIL_BULL, T_RAIL_OUTER)) or (name == 'Body' and t == T_SKIRT):
                h = (n[1], -n[0], 0.0)
                if math.hypot(h[0], h[1]) > 1e-6:
                    expect = vunit(h)
            elif name == 'Body' and t in (T_BLOCK, T_LEG) and abs(n[2]) < 0.5:
                zdir = (-n[2] * n[0], -n[2] * n[1], 1 - n[2] * n[2])
                expect = vunit(zdir)
            if expect is not None and tan is not None:
                cg = abs(sum(a * b for a, b in zip(tan, expect)))
                if cg < grain_worst:
                    grain_worst = cg
                    grain_at = (t, [round(sum(q[j] for q in pts) / 3, 3) for j in range(3)])
        rule_ok = True
        for tags, kind, tolkey in UV_RULES.get(name, []):
            key = kind + ('' if tolkey is None else ':' + tolkey)
            if key not in dens:
                continue
            lo, hi = dens[key]
            if tolkey is None:
                rule_ok = rule_ok and lo >= target[kind]
            else:
                tl = p[tolkey]
                rule_ok = rule_ok and lo >= target[kind] * (1 - tl) and hi <= target[kind] * (1 + tl)
        grain_ok = grain_worst >= p['grain_min_cos'] if name in ('Rails', 'Body') else True
        stats[name] = {'px_per_stud': {k: [round(a, 1), round(b, 1)] for k, (a, b) in dens.items()},
                       'mirrored_faces': mirrored, 'mirrored_by_tag': bad_tags, 'grain_worst_at': grain_at,
                       'px_per_stud_by_tag': {str(k): [round(a, 1), round(b, 1)] for k, (a, b) in sorted(tag_dens.items())},
                       'grain_min_abs_cos': grain_worst if name in ('Rails', 'Body') else None,
                       'ok': rule_ok and grain_ok and mirrored == 0}
        mirrored_total += mirrored
        ok = ok and stats[name]['ok']
    # logo plate: the front face spans UV 0..1; the plate is logo_size, so the image is that aspect
    lp = data['LogoPlate']
    front = [i for pl, t in zip(lp.polys, lp.tags) if t == T_LOGO_FRONT for i in pl]
    ys = [lp.co[i][1] for i in front]
    zs = [lp.co[i][2] for i in front]
    world_aspect = (max(ys) - min(ys)) / (max(zs) - min(zs))
    image_aspect = p['logo_size'][0] / p['logo_size'][1]
    err = abs(world_aspect / image_aspect - 1)
    stats['LogoPlate']['front_aspect_error'] = err
    stats['LogoPlate']['ok'] = stats['LogoPlate']['ok'] and err <= p['logo_aspect_tolerance']
    ok = ok and stats['LogoPlate']['ok']
    return stats, ok


