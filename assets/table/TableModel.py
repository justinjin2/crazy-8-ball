def arc_lengths(pts, anchor):
    """Cumulative arc length along pts, shifted so vertex `anchor` sits at 0."""
    s = [0.0]
    for a, b in zip(pts, pts[1:]):
        s.append(s[-1] + math.dist(a, b))
    return [x - s[anchor] for x in s]


def build_cushion(L, part, c, kc):
    levels = L.levels
    curves = [L.cushion_curve(c, e)[0] for e, _ in levels]
    kinds = L.cushion_curve(c, 0.0)[1]
    n = len(curves[0])
    i_m1 = kinds.index('facing')  # the two mitres (nose points) are the only 'facing' vertices
    i_m2 = i_m1 + 1
    assert kinds[i_m2] == 'facing'
    nose = curves[L.nose_level]
    mid = mul(add(nose[i_m1], nose[i_m2]), 0.5)
    u_mid = arc_lengths(nose, i_m1)[i_m1] + math.dist(nose[i_m1], mid)
    us = []
    for curve in curves:  # per level arc length, anchored at the rail midpoint (shear, not stretch)
        m = mul(add(curve[i_m1], curve[i_m2]), 0.5)
        s = arc_lengths(curve, i_m1)
        us.append([u_mid + x - math.dist(curve[i_m1], m) for x in s])
    V = L.level_v
    rail0 = L.segs[c['rail']]
    # u must turn the right way round the outward normal: flip it when the table is on the left
    usgn = 1.0 if cross(unit(sub(tuple(rail0['b']), tuple(rail0['a']))), tuple(rail0['normal'])) < 0 else -1.0
    us = [[usgn * x for x in row] for row in us]
    u_mid *= usgn
    idx = [[part.v((x, y, z)) for x, y in curve] for curve, (_, z) in zip(curves, levels)]
    start = len(part.faces)
    ref = None
    for k in range(len(levels) - 1):
        for i in range(n - 1):
            straight = kinds[i] == 'facing' or kinds[i + 1] == 'facing' or \
                (kinds[i] == 'fillet' and kinds[i + 1] == 'facing')
            tag = T_CUSHION if straight else T_KNOB
            uvs = [(us[k][i] * kc, V[k] * kc), (us[k][i + 1] * kc, V[k] * kc),
                   (us[k + 1][i + 1] * kc, V[k + 1] * kc), (us[k + 1][i] * kc, V[k + 1] * kc)]
            if k == L.nose_level - 1 and i == i_m1:
                ref = len(part.faces)
            part.quad(idx[k][i], idx[k][i + 1], idx[k + 1][i + 1], idx[k + 1][i], uvs, tag)
    rail = L.segs[c['rail']]
    if dot(part.face_normal(ref)[:2], tuple(rail['normal'])) < 0:
        part.flip(start)
    # Top: the plane from the upper rounding level up to the back line, and the facing walls.
    upper = curves[-1]
    top_idx = []
    for i, pt in enumerate(upper):
        if i in (i_m1, i_m2):
            top_idx.append(idx[-1][i])
        else:
            top_idx.append(part.v((pt[0], pt[1], L.top_z(c, pt))))
    dr = unit(sub(tuple(rail['b']), tuple(rail['a'])))
    kv = sqrt(1 + L.slope ** 2)

    def top_uv(pt):
        return ((u_mid + usgn * dot(sub(pt, mid), dr)) * kc, (V[-1] + (L.rail_depth(c, pt) - L.eU) * kv) * kc)

    _, tris = tc.triangulate(upper)
    start = len(part.faces)
    for tri in tris:
        part.f([top_idx[i] for i in tri], [top_uv(upper[i]) for i in tri], T_CUSHION_TOP)
    if part.face_normal(start)[2] < 0:
        part.flip(start)
    start = len(part.faces)
    ref = None
    for i in list(range(0, i_m1)) + list(range(i_m2, n - 1)):
        a, b = idx[-1][i], idx[-1][i + 1]
        ta, tb = top_idx[i], top_idx[i + 1]
        za, zb = L.top_z(c, upper[i]), L.top_z(c, upper[i + 1])
        ua, ub = us[-1][i] * kc, us[-1][i + 1] * kc
        v0 = V[-1] * kc
        if tb == b:
            part.f((a, b, ta), [(ua, v0), (ub, v0), (ua, v0 + (za - L.zU) * kc)], T_FACING_WALL)
        elif ta == a:
            part.f((a, b, tb), [(ua, v0), (ub, v0), (ub, v0 + (zb - L.zU) * kc)], T_FACING_WALL)
        else:
            part.quad(a, b, tb, ta, [(ua, v0), (ub, v0), (ub, v0 + (zb - L.zU) * kc),
                                     (ua, v0 + (za - L.zU) * kc)], T_FACING_WALL)
        if ref is None and i >= i_m2:
            ref = len(part.faces) - 1
    # The wall beside the second facing must face into its throat.
    e2 = L.ends[c['facings'][1]]
    if dot(part.face_normal(ref)[:2], e2.nf) < 0:
        part.flip(start)
    # Back face along the back line (against the rail's inner face; closes the cushion where the
    # rail gives way to the pocket rim between the heel and the rim).
    p1, p2 = upper[0], upper[-1]
    z0 = levels[0][1]
    ids = [idx[0][0], idx[0][-1], top_idx[-1], top_idx[0]]
    pts = [part.co[i] for i in ids]
    back_n = mul(tuple(rail['normal']), -1)
    bu = [(dot(q[:2], dr) * kc * usgn, q[2] * kc) for q in pts]
    start = len(part.faces)
    part.f(ids, bu, T_CUSHION_BACK)
    if dot(part.face_normal(start)[:2], back_n) < 0:
        part.flip(start)
    part.fix_uv_sign(start)
    return curves


def perimeter_order(L):
    """Cushions in order round the table, each with a flag: True when it runs pockets[1] -> [2]."""
    order = [(L.cushions[0], True)]
    pocket = L.cushions[0]['pockets'][1]
    while len(order) < 6:
        for c in L.cushions:
            if any(c is o for o, _ in order):
                continue
            if c['pockets'][0] == pocket:
                order.append((c, True))
                pocket = c['pockets'][1]
                break
            if c['pockets'][1] == pocket:
                order.append((c, False))
                pocket = c['pockets'][0]
                break
        else:
            raise AssertionError('cushions do not form a loop')
    return order


def clip_into_disc(curve, centre, radius):
    """Walk from the middle of curve to its end; stop where it first enters the disc. Returns
    (points kept, the entry point). Without an entry, heads from the last point to the centre."""
    hit = None
    for i in range(len(curve) - 1):
        a, b = curve[i], curve[i + 1]
        if math.dist(a, centre) >= radius > math.dist(b, centre):
            hit = i
    if hit is not None:
        a, b = curve[hit], curve[hit + 1]
        d = unit(sub(b, a))
        roots = line_circle(a, d, centre, radius)
        s_ = min(r for r in roots if r >= -1e-12)
        return curve[:hit + 1], add(a, mul(d, s_))
    last = curve[-1]
    assert math.dist(last, centre) > radius
    return curve, add(centre, mul(unit(sub(last, centre)), radius))


def mouth_samples(L, pk, xa, xb):
    """Angles about the hole centre from xa to xb through the table side (fine tolerance)."""
    a0 = ang(sub(xa, pk.H))
    span = L.mouth_span(pk, a0, ang(sub(xb, pk.H)))
    n = arc_steps(pk.r, span, L.p['chord_tol_fine'])
    return a0, span, n


def build_bed_and_rolls(L, part, kc):
    p = L.p
    rb_extra = p['roll_radius']
    order = perimeter_order(L)
    curves = []
    for c, forward in order:
        pts = L.cushion_curve(c, L.e_bed)[0]
        curves.append(pts if forward else list(reversed(pts)))
    pockets_in_order = []
    for (c, forward) in order:
        pockets_in_order.append(c['pockets'][1] if forward else c['pockets'][0])
    loop = []
    mouths = []
    heads = []
    for k in range(6):
        pk = L.pockets[pockets_in_order[k - 1]]
        rev = list(reversed(curves[k]))
        kept, x = clip_into_disc(rev, pk.H, pk.r + rb_extra)
        heads.append((list(reversed(kept)), x))
    for k in range(6):
        pk = L.pockets[pockets_in_order[k]]
        head_pts, head_x = heads[k]
        # this cushion's run from the previous pocket's entry point to this pocket's entry point
        body = head_pts
        kept, tail_x = clip_into_disc(body, pk.H, pk.r + rb_extra)
        loop += [head_x] + kept + [tail_x]
        next_head_x = heads[(k + 1) % 6][1]
        a0, span, n = mouth_samples(L, pk, tail_x, next_head_x)
        rb = pk.r + rb_extra
        arc_pts = [polar(pk.H, rb, a0 + span * j / n) for j in range(1, n)]
        loop += arc_pts
        mouths.append((pk, a0, span, n, tail_x, next_head_x))
    # remove exact repeats (a clipped curve can start on its own entry point)
    clean_loop = []
    for q in loop:
        if not clean_loop or math.dist(q, clean_loop[-1]) > 1e-9:
            clean_loop.append(q)
    if math.dist(clean_loop[0], clean_loop[-1]) < 1e-9:
        clean_loop.pop()
    verts, tris = tc.triangulate(clean_loop)
    ids = [part.v((x, y, 0.0)) for x, y in verts]
    for tri in tris:
        part.f([ids[i] for i in tri], [(verts[i][0] * kc, verts[i][1] * kc) for i in tri], T_BED)
    # Rolls: flat cloth ends at radius + rho, turns vertical at radius, bore, then tucks behind the cup.
    rho = p['roll_radius']
    n_roll = arc_steps(rho, pi / 2, p['chord_tol_fine'])
    for pk, a0, span, n, xa, xb in mouths:
        rv_fac = (1 + 1 / cos(abs(span) / n / 2)) / 2
        prof = [(pk.r + rho, 0.0)]
        for j in range(1, n_roll + 1):
            beta = pi / 2 + (pi / 2) * j / n_roll
            prof.append((pk.r + rho + rho * cos(beta), -rho + rho * sin(beta)))
        prof.append((pk.r, -rho - p['bore_depth']))
        prof.append((pk.r + p['tuck_out'], -rho - p['bore_depth'] - p['tuck_drop']))
        pv = [0.0]
        for a, b in zip(prof, prof[1:]):
            pv.append(pv[-1] + math.dist(a, b))
        grid = []
        for j in range(n + 1):
            phi = a0 + span * j / n
            fac = 1.0 if j in (0, n) else rv_fac
            col = []
            for m, (rad, z) in enumerate(prof):
                if m == 0:
                    rr = rad
                elif rad <= pk.r + 1e-12:
                    rr = pk.r * fac  # the vertical ring straddles the physics circle
                else:
                    rr = rad
                col.append(part.v(polar(pk.H, rr, phi) + (z,)))
            grid.append(col)
        start = len(part.faces)
        for j in range(n):
            u0, u1 = -span * pk.r * j / n * kc, -span * pk.r * (j + 1) / n * kc
            for m in range(len(prof) - 1):
                part.quad(grid[j][m], grid[j + 1][m], grid[j + 1][m + 1], grid[j][m + 1],
                          [(u0, -pv[m] * kc), (u1, -pv[m] * kc), (u1, -pv[m + 1] * kc), (u0, -pv[m + 1] * kc)],
                          T_ROLL)
        # the vertical part must face the hole axis
        k_ref = start + (n // 2) * (len(prof) - 1) + n_roll
        nrm = part.face_normal(k_ref)
        mid_dir = (cos(a0 + span / 2), sin(a0 + span / 2))
        if dot(nrm[:2], mid_dir) > 0:
            part.flip(start)
    return clean_loop, mouths


def build_cloth(L):
    kc = L.s / L.p['cloth_studs_per_repeat']
    part = Part('Cloth')
    L.cushion_curves = {}
    for c in L.cushions:
        L.cushion_curves[c['rail']] = build_cushion(L, part, c, kc)
    L.bed_loop, L.mouths = build_bed_and_rolls(L, part, kc)
    return [part]


