def check_clearances(L, data):
    p = L.p
    pockets = data['Pockets']
    cup = [pockets.co[i] for pl, t in zip(pockets.polys, pockets.tags) if t in (T_CUP, T_CUP_FLOOR) for i in pl]
    X = L.X0 - p['skirt_inset'] - p['skirt_thickness']
    Y = L.Y0 - p['skirt_inset'] - p['skirt_thickness']
    S = p['cabinet_clip_sum']
    margin = min(min(X - abs(q[0]) for q in cup), min(Y - abs(q[1]) for q in cup),
                 min((S - abs(q[0]) - abs(q[1])) / sqrt(2) for q in cup))
    depth = -min(q[2] for q in cup)
    bx = L.g['rail']['barrier_half_extents_studs'][0] / L.s
    by = L.g['rail']['barrier_half_extents_studs'][1] / L.s
    worst_x = max(abs(q[0]) for md in data.values() for q in md.co)
    worst_y = max(abs(q[1]) for md in data.values() for q in md.co)
    marks = data['Marks']
    marks_margin = min(math.dist(q[:2], pk.H) - (pk.r + L.p['roll_radius'])
                       for q in marks.co for pk in L.pockets.values())
    marks_lift = min(q[2] for q in marks.co) * L.s
    out = {'marks_min_margin_outside_hole_rims': marks_margin, 'marks_lift_studs': marks_lift,
           'cup_margin_to_skirt_and_cabinet': margin, 'cup_depth': depth,
           'max_abs_x': worst_x, 'max_abs_y': worst_y, 'outer_half': [L.X0, L.Y0], 'barrier_half': [bx, by]}
    out["ok"] = (marks_margin >= -1e-5 and abs(marks_lift - L.p['marks_lift_studs']) < 1e-6 and margin >= 0.25 - 1e-9 and depth >= L.g['pockets']['min_depth'] and
                 worst_x <= L.X0 + 1e-5 and worst_y <= L.Y0 + 1e-5 and worst_x <= bx and worst_y <= by)
    return out


def check_gaps(L, meshes, label):
    """Rays from straight above and at 30 degrees from 8 directions must hit a front face."""
    p = L.p
    bvh, co, ftags = bvh_of(meshes)
    dirs = [Vector((0, 0, -1))]
    for k in range(8):
        az = 2 * pi * k / 8
        dirs.append(Vector((cos(az) * cos(radians(30)), sin(az) * cos(radians(30)), -sin(radians(30)))))
    lim_x, lim_y = L.X0 - 1.0, L.Y0 - 1.0
    lim_s = L.X0 + L.Y0 - p['corner_clip'] - 1.5
    targets = []
    for x in frange(-lim_x, lim_x, p['gap_grid']):
        for y in frange(-lim_y, lim_y, p['gap_grid']):
            if abs(x) + abs(y) <= lim_s:
                targets.append((x, y))
    for pk in L.pockets.values():
        for x in frange(pk.H[0] - 6, pk.H[0] + 6, p['gap_grid_pocket']):
            for y in frange(pk.H[1] - 6, pk.H[1] + 6, p['gap_grid_pocket']):
                if abs(x) <= lim_x and abs(y) <= lim_y and abs(x) + abs(y) <= lim_s:
                    targets.append((x, y))
    miss, back, casts = 0, 0, 0
    first = []
    for x, y in targets:
        tgt = Vector((x + 0.0137, y + 0.0071, 0.0))  # off the exact vertex grid
        for d in dirs:
            origin = tgt - d * 60.0
            loc, nrm, idx, dist = bvh.ray_cast(origin, d)
            casts += 1
            if loc is None:
                miss += 1
                if len(first) < 8:
                    first.append(('miss', round(x, 2), round(y, 2), tuple(round(c, 2) for c in d)))
            elif nrm.dot(d) >= -1e-4:
                back += 1
                if len(first) < 8:
                    first.append(('back', round(loc.x, 3), round(loc.y, 3), round(loc.z, 3), tuple(round(c, 2) for c in d),
                                  ftags[idx]))
    return {'label': label, 'rays': casts, 'misses': miss, 'back_faces': back, 'first_failures': first,
            'ok': miss == 0 and back == 0}


def uv_tangent(pts, uvs):
    """dP/du of a triangle (3D, normalised) and the signed UV area."""
    e1 = [pts[1][j] - pts[0][j] for j in range(3)]
    e2 = [pts[2][j] - pts[0][j] for j in range(3)]
    du1, dv1 = uvs[1][0] - uvs[0][0], uvs[1][1] - uvs[0][1]
    du2, dv2 = uvs[2][0] - uvs[0][0], uvs[2][1] - uvs[0][1]
    det = du1 * dv2 - du2 * dv1
    if abs(det) < 1e-18:
        return None, 0.0
    t = [(dv2 * e1[j] - dv1 * e2[j]) / det for j in range(3)]
    n = math.sqrt(sum(c * c for c in t))
    return (tuple(c / n for c in t) if n > 0 else None), det / 2


