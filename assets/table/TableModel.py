def plane_uv(pts, normal, scale, origin=(0.0, 0.0)):
    """Orientation-preserving planar UVs for a flat face with this outward normal."""
    n = normal
    ref = (0.0, 0.0, 1.0) if abs(n[2]) < 0.9 else (1.0, 0.0, 0.0)
    t1 = (ref[1] * n[2] - ref[2] * n[1], ref[2] * n[0] - ref[0] * n[2], ref[0] * n[1] - ref[1] * n[0])
    ln = math.sqrt(sum(c * c for c in t1))
    t1 = tuple(c / ln for c in t1)
    t2 = (n[1] * t1[2] - n[2] * t1[1], n[2] * t1[0] - n[0] * t1[2], n[0] * t1[1] - n[1] * t1[0])
    return [(origin[0] + sum(a * b for a, b in zip(q, t1)) * scale,
             origin[1] + sum(a * b for a, b in zip(q, t2)) * scale) for q in pts]


def prism(part, rings, tag_side, tag_cap, side_uv, cap_scale, cap_origin, caps=(True, True), cap_tags=None):
    """Closed prism through CCW (seen from above) plan rings [(z, [points])], top ring first.
    side_uv(face points, outward normal) gives the UVs of each side quad."""
    ids = [[part.vk((q[0], q[1], z)) for q in pts] for z, pts in rings]
    n = len(rings[0][1])
    for k in range(len(rings) - 1):
        for i in range(n):
            i2 = (i + 1) % n
            quad = [ids[k][i], ids[k + 1][i], ids[k + 1][i2], ids[k][i2]]
            pts = [part.co[j] for j in quad]
            d = sub(rings[k][1][i2], rings[k][1][i])
            nrm = unit((d[1], -d[0]))
            flat = abs(rings[k][0] - rings[k + 1][0]) < 1e-9
            if flat and length(sub(rings[k][1][i], rings[k + 1][1][i])) < 1e-9 and \
                    length(sub(rings[k][1][i2], rings[k + 1][1][i2])) < 1e-9:
                continue
            if flat:
                cx_ = sum(q[0] for q in rings[k][1]) / n
                cy_ = sum(q[1] for q in rings[k][1]) / n
                up = math.dist(rings[k + 1][1][i], (cx_, cy_)) < math.dist(rings[k][1][i], (cx_, cy_))
                nz = (0.0, 0.0, -1.0 if up else 1.0)
                part.f(quad, plane_uv(pts, nz, cap_scale, cap_origin), tag_side)
            else:
                part.f(quad, side_uv(pts, (nrm[0], nrm[1], 0.0)), tag_side)
    tags = cap_tags or (tag_cap, tag_cap)
    if caps[0]:
        pts = [part.co[j] for j in ids[0]]
        part.f(ids[0], plane_uv(pts, (0, 0, 1), cap_scale, cap_origin), tags[0])
    if caps[1]:
        pts = [part.co[j] for j in reversed(ids[-1])]
        part.f(list(reversed(ids[-1])), plane_uv(pts, (0, 0, -1), cap_scale, cap_origin), tags[1])
    return ids


def vertical_grain_uv(scale, v0):
    """Grain up the face: u follows z, v runs across the face (orientation-preserving)."""
    def uv(pts, nrm):
        h = (nrm[1], -nrm[0])
        base = min(dot(q[:2], h) for q in pts)
        return [(0.5 + q[2] * scale, v0 + (dot(q[:2], h) - base) * scale) for q in pts]
    return uv


def build_skirt(L, kb):
    p = L.p
    parts = []
    top_s = p['rail_bottom']
    bot = top_s - p['skirt_height']
    b = p['skirt_bead']
    ch = p['skirt_top_chamfer']
    th = p['skirt_thickness']
    sv0, _ = BODY_V['skirt']
    for outward in ((0, 1), (0, -1), (1, 0), (-1, 0)):
        Q = (L.X0 if outward[0] else L.Y0) - p['skirt_inset']
        run = p['skirt_end'] if outward[1] else p['skirt_end_y']
        a = (outward[1], -outward[0])  # along the panel, grain direction (right of outward)
        prof = [(Q - th, top_s), (Q - ch, top_s), (Q, top_s - ch), (Q, bot + 0.3), (Q + 0.6 * b, bot + 0.26),
                (Q + b, bot + 0.17), (Q + 0.85 * b, bot + 0.08), (Q + 0.35 * b, bot + 0.02), (Q - 0.03, bot),
                (Q - th, bot)]
        arcv = [0.0]
        for q0, q1 in zip(prof, prof[1:]):
            arcv.append(arcv[-1] + math.dist(q0, q1))
        part = Part('Skirt', closed=True)

        def pt(qd, z, s_):
            return add(mul(outward, qd), mul(a, s_)) + (z,)
        ids0 = [part.vk(pt(qd, z, -run)) for qd, z in prof]
        ids1 = [part.vk(pt(qd, z, run)) for qd, z in prof]
        m = len(prof)
        for j in range(m):
            j2 = (j + 1) % m
            visible = 1 <= j <= m - 2
            if visible:
                uvs = [(-run * kb, sv0 + arcv[j] * kb), (run * kb, sv0 + arcv[j] * kb),
                       (run * kb, sv0 + arcv[j2] * kb), (-run * kb, sv0 + arcv[j2] * kb)]
                part.quad(ids0[j], ids1[j], ids1[j2], ids0[j2], uvs, T_SKIRT)
            else:
                pts = [part.co[i] for i in (ids0[j], ids1[j], ids1[j2], ids0[j2])]
                h0, _ = BODY_V['hidden']
                part.quad(ids0[j], ids1[j], ids1[j2], ids0[j2],
                          plane_uv(pts, (-outward[0], -outward[1], 0) if j == m - 1 else (0, 0, 1),
                                   kb * p['hidden_uv_scale'], (0.5, h0 + 0.03)), T_SKIRT_HIDDEN)
        h0, _ = BODY_V['hidden']
        for ids, sgn in ((ids0, -1), (ids1, 1)):
            pts = [part.co[i] for i in ids]
            part.f(ids, plane_uv(pts, (a[0] * sgn, a[1] * sgn, 0), kb * p['hidden_uv_scale'], (0.2, h0 + 0.03)),
                   T_SKIRT_HIDDEN)
        parts.append(part)
    return parts


def cabinet_plan(L):
    p = L.p
    X = L.X0 - p['skirt_inset'] - p['skirt_thickness']
    Y = L.Y0 - p['skirt_inset'] - p['skirt_thickness']
    S = p['cabinet_clip_sum']
    return [(X, S - X), (S - Y, Y), (-(S - Y), Y), (-X, S - X), (-X, -(S - X)), (-(S - Y), -Y), (S - Y, -Y),
            (X, -(S - X))]


def build_cabinet(L, kb):
    p = L.p
    part = Part('Cabinet')
    ztop = p['rail_bottom'] - p['skirt_height']
    zbot = ztop - p['cabinet_visible']
    plan = cabinet_plan(L)
    top = [part.v((q[0], q[1], ztop)) for q in plan]
    bot = [part.v((q[0], q[1], zbot)) for q in plan]
    cv0, _ = BODY_V['cabinet']
    s_acc = 0.0
    for i in range(len(plan)):
        i2 = (i + 1) % len(plan)
        seg = math.dist(plan[i], plan[i2])
        # CCW plan: the outward normal is on the right of each edge; u runs against the edge
        u0, u1 = -s_acc * kb, -(s_acc + seg) * kb
        part.quad(top[i], bot[i], bot[i2], top[i2],
                  [(u0, cv0), (u0, cv0 + (ztop - zbot) * kb), (u1, cv0 + (ztop - zbot) * kb), (u1, cv0)], T_CABINET)
        s_acc += seg
    h0, _ = BODY_V['hidden']
    pts = [part.co[i] for i in reversed(bot)]
    part.f(list(reversed(bot)), plane_uv(pts, (0, 0, -1), kb * p['hidden_uv_scale'], (0.5, h0 + 0.05)),
           T_CABINET_BOTTOM)
    return part


def block_plan(L, corner, w):
    """CCW L-shaped plan of a corner block (the (+,+) template mirrored), arm length w."""
    p = L.p
    X, Y = L.X0, L.Y0
    t = p['skirt_inset'] + p['skirt_thickness']
    ce = p['block_edge_chamfer']
    clip = p['corner_clip']
    S_in = X + Y - clip - p['block_facet_thickness'] * sqrt(2)
    tmpl = [(X - w, Y - t), (X - w, Y - ce), (X - w + ce, Y), (X - clip, Y), (X, Y - clip), (X, Y - w + ce),
            (X - ce, Y - w), (X - t, Y - w), (X - t, S_in - (X - t)), (S_in - (Y - t), Y - t)]
    # template is clockwise; reverse for CCW
    tmpl = list(reversed(tmpl))
    sx, sy = corner
    pts = [(sx * x, sy * y) for x, y in tmpl]
    if sx * sy < 0:
        pts = list(reversed(pts))
    return pts


def leg_plan(L, corner, a, inset=0.0):
    p = L.p
    sx, sy = corner
    cx = L.X0 - p['skirt_inset'] - p['leg_top'] / 2
    cy = L.Y0 - p['skirt_inset'] - p['leg_top'] / 2
    f = a / (p['leg_top'] / 2)
    c1 = p['leg_chamfer'] * f
    k = p['leg_clip'] * f
    a = a - inset
    tmpl = [(-a + c1, -a), (a - c1, -a), (a, -a + c1), (a, a - k), (a - k, a), (-a + c1, a), (-a, a - c1),
            (-a, -a + c1)]
    pts = [(sx * (cx + x), sy * (cy + y)) for x, y in tmpl]
    if sx * sy < 0:
        pts = list(reversed(pts))
    return pts


def leg_levels(L):
    p = L.p
    z_top = p['rail_bottom'] - p['skirt_height'] - p['cabinet_visible']
    z_floor = -L.g['cloth']['above_floor']
    z_seam = z_top + (z_floor - z_top) * p['leg_seam_fraction']
    z_foot = z_floor + p['leveller_height']
    return z_top, z_seam, z_foot, z_floor


def leg_half(L, z):
    p = L.p
    z_top, _, _, z_floor = leg_levels(L)
    t = (z_top - z) / (z_top - z_floor)
    return (p['leg_top'] + (p['leg_bottom'] - p['leg_top']) * t) / 2


def build_body(L):
    p = L.p
    kb = p['body_px_per_stud'] / p['atlas_px'] * L.s
    parts = build_skirt(L, kb)
    parts.append(build_cabinet(L, kb))
    z_top = p['rail_bottom']
    z_bot = z_top - p['skirt_height'] - p['cabinet_visible']
    hs = kb * p['hidden_uv_scale']
    h0, _ = BODY_V['hidden']
    lz_top, z_seam, z_foot, z_floor = leg_levels(L)
    g = p['leg_groove']
    for corner in CORNERS:
        part = Part('Block', closed=True)
        rings = [(z_top, block_plan(L, corner, p['block_width_top'])),
                 (z_bot, block_plan(L, corner, p['block_width_bottom']))]
        prism(part, rings, T_BLOCK, T_BLOCK_HIDDEN, vertical_grain_uv(kb, BODY_V['block'][0]), hs, (0.3, h0 + 0.05))
        parts.append(part)
        leg = Part('Leg', closed=True)
        levels = [(lz_top, 0.0), (z_seam + g / 2, 0.0), (z_seam + g / 2, g), (z_seam - g / 2, g),
                  (z_seam - g / 2, 0.0), (z_foot, 0.0)]
        rings = [(z, leg_plan(L, corner, leg_half(L, z), inset)) for z, inset in levels]
        prism(leg, rings, T_LEG, T_LEG_HIDDEN, vertical_grain_uv(kb, BODY_V['leg'][0]), kb, (0.6, BODY_V['leg'][0]),
              cap_tags=(T_LEG_HIDDEN, T_LEG))
        # the hidden top gets squashed UVs
        parts.append(leg)
        lev = Part('Leveller', closed=True)
        sx, sy = corner
        cx = sx * (L.X0 - p['skirt_inset'] - p['leg_top'] / 2)
        cy = sy * (L.Y0 - p['skirt_inset'] - p['leg_top'] / 2)
        hlv = p['leveller_size'] / 2
        c1 = 0.12
        sq = [(cx - hlv + c1, cy - hlv), (cx + hlv - c1, cy - hlv), (cx + hlv, cy - hlv + c1), (cx + hlv, cy + hlv - c1),
              (cx + hlv - c1, cy + hlv), (cx - hlv + c1, cy + hlv), (cx - hlv, cy + hlv - c1), (cx - hlv, cy - hlv + c1)]
        lv0, _ = BODY_V['leveller']

        def lev_uv(pts, nrm):
            hh = (nrm[1], -nrm[0])
            base = min(dot(q[:2], hh) for q in pts)
            return [(0.2 + (dot(q[:2], hh) - base) * kb, lv0 + (z_foot + p['leveller_sink'] - q[2]) * kb) for q in pts]
        prism(lev, [(z_foot + p['leveller_sink'], sq), (z_floor, sq)], T_LEVELLER, T_LEVELLER_HIDDEN, lev_uv, hs,
              (0.4, h0 + 0.05))
        parts.append(lev)
    return parts


