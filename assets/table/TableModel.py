def cap_profile(L, pk, h):
    """(w, z, part) round the cap section, w measured out from the opening circle."""
    p = L.p
    zb = L.top + p['cap_gap']
    wo = pk.w + p['cap_over_wood']
    return [(wo, zb, 'u'), (wo - 0.015, zb + 0.5 * h, 't'), (wo - 0.08, zb + 0.9 * h, 't'),
            (wo * 0.45, zb + h, 't'), (0.02, zb + 0.8 * h, 't'), (-p['cap_lip'], zb + 0.3 * h, 't'),
            (-0.02, L.top - 0.03, 'u'), (0.05, L.top - 0.002, 'u'), (p['rim_roll'], zb, 'u')]


def build_cap(L, part, pk):
    p = L.p
    kp = p['parts_px_per_stud'] / p['atlas_px'] * L.s
    over = p['cap_end_overrun'][pk.kind] / pk.Rc
    sgn = math.copysign(1, pk.span)
    cand = [ang(sub(q, pk.Hp)) for q in (pk.EA, pk.FA)]
    rel = [((a - pk.psiA) * sgn) % (2 * pi) for a in cand]
    rel = [r - 2 * pi if r > pi else r for r in rel]
    t0 = min(rel) - over
    candB = [ang(sub(q, pk.Hp)) for q in (pk.EB, pk.FB)]
    relB = [((a - pk.psiA) * sgn) % (2 * pi) for a in candB]
    t1 = max(relB) + over
    n = p['cap_sections'][pk.kind]
    zb = L.top + p['cap_gap']
    h_target = p['casting_top_target'] - zb
    base = cap_profile(L, pk, 1.0)
    sections, heights = [], []
    for k in range(n + 1):
        psi = pk.psiA + sgn * (t0 + (t1 - t0) * k / n)
        dirn = (cos(psi), sin(psi))
        h = h_target
        for w, z, _ in base:
            shape = z - zb
            if shape > 1e-9:
                d = math.dist(add(pk.Hp, mul(dirn, pk.Rc + w)), pk.H)
                h = min(h, (L.casting_limit(d) - zb) / shape - 1e-6)
        heights.append(h)
        prof = cap_profile(L, pk, h)
        sections.append([part.vk(add(pk.Hp, mul(dirn, pk.Rc + w)) + (z,)) for w, z, _ in prof])
    tv0, _ = PARTS_V['chrome']
    uv0, _ = PARTS_V['chrome_under']
    prof = cap_profile(L, pk, h_target)
    m = len(prof)
    arcl = [0.0]
    for a, b in zip(prof, prof[1:] + prof[:1]):
        arcl.append(arcl[-1] + math.hypot(b[0] - a[0], b[1] - a[1]))
    for k in range(n):
        u0 = 0.05 + (t0 + (t1 - t0) * k / n) * pk.Rc * kp
        u1 = 0.05 + (t0 + (t1 - t0) * (k + 1) / n) * pk.Rc * kp
        if sgn < 0:
            u0, u1 = -u0, -u1
        for j in range(m):
            j2 = (j + 1) % m
            under = prof[j][2] == 'u' and prof[j2][2] == 'u'
            v0 = (uv0 if under else tv0) + arcl[j] * kp
            v1 = (uv0 if under else tv0) + arcl[j + 1] * kp
            part.quad(sections[k][j], sections[k + 1][j], sections[k + 1][j2], sections[k][j2],
                      [(u0, v0), (u1, v0), (u1, v1), (u0, v1)], T_CAP_UNDER if under else T_CAP_TOP)
    for which, sec in ((0, sections[0]), (1, sections[-1])):
        prof_k = cap_profile(L, pk, heights[0 if which == 0 else -1])
        sign = 1 if which == 0 else -1
        uvs = [(0.8 + sign * w * kp * sgn, tv0 + (z - L.top + 0.05) * kp) for w, z, _ in prof_k]
        part.f(sec, uvs, T_CAP_END)
    return max(heights)


def build_caps(L):
    parts = []
    for hid in sorted(L.pockets):
        part = Part('Cap%d' % hid, closed=True)
        build_cap(L, part, L.pockets[hid])
        parts.append(part)
    return parts


