CLOSED_MESHES = {'Rails', 'Caps', 'Hardware', 'LogoPlate'}


def components(md):
    parent = list(range(len(md.co)))

    def find(i):
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i
    for pl in md.polys:
        r0 = find(pl[0])
        for i in pl[1:]:
            ri = find(i)
            if ri != r0:
                parent[ri] = r0
    comp = {}
    for k, pl in enumerate(md.polys):
        comp.setdefault(find(pl[0]), []).append(k)
    return list(comp.values())


def check_topology(md, L, phys):
    p = L.p
    s2 = L.s * L.s
    report = {'triangles': len(md.polys)}
    report['non_triangles'] = sum(1 for pl in md.polys if len(pl) != 3)
    zero = 0
    for pl in md.polys:
        area, _ = tri_area3(*(md.co[i] for i in pl))
        if area * s2 < p['min_face_area_studs']:
            zero += 1
    report['zero_area_faces'] = zero
    used = set(i for pl in md.polys for i in pl)
    report['loose_vertices'] = len(md.co) - len(used)
    comps = components(md)
    report['components'] = len(comps)
    closed_bad, open_bad, neg = 0, 0, 0
    boundary_total, nonmanifold = 0, 0
    min_volume = None
    for faces in comps:
        edges = {}
        for k in faces:
            pl = md.polys[k]
            for a, b in zip(pl, pl[1:] + pl[:1]):
                key = (min(a, b), max(a, b))
                edges[key] = edges.get(key, 0) + 1
        bnd = [e for e, n in edges.items() if n == 1]
        nonmanifold += sum(1 for n in edges.values() if n > 2)
        boundary_total += len(bnd)
        tags = set(md.tags[k] for k in faces)
        must_close = md.name in CLOSED_MESHES or (md.name == 'Body' and T_CABINET not in tags)
        if must_close:
            vol = 0.0
            for k in faces:
                a, b, c = (md.co[i] for i in md.polys[k])
                vol += (a[0] * (b[1] * c[2] - b[2] * c[1]) - a[1] * (b[0] * c[2] - b[2] * c[0])
                        + a[2] * (b[0] * c[1] - b[1] * c[0])) / 6.0
            min_volume = vol if min_volume is None else min(min_volume, vol)
            if bnd:
                closed_bad += 1
            if vol <= 0:
                neg += 1
        else:
            for a, b in bnd:
                qa, qb = md.co[a], md.co[b]
                mid = ((qa[0] + qb[0]) / 2, (qa[1] + qb[1]) / 2, (qa[2] + qb[2]) / 2)
                if not expected_boundary(md.name, mid, tags, L, phys):
                    open_bad += 1
    report.update({'boundary_edges': boundary_total, 'non_manifold_edges': nonmanifold,
                   'open_closed_shells': closed_bad, 'non_positive_volumes': neg,
                   'unexpected_boundary_edges': open_bad,
                   'min_shell_volume_cubic_inches': min_volume})
    ok = (report['non_triangles'] == 0 and zero == 0 and report['loose_vertices'] == 0 and nonmanifold == 0
          and closed_bad == 0 and neg == 0 and open_bad == 0)
    report['ok'] = ok
    return report


def expected_boundary(name, mid, tags, L, phys):
    """Open sheets may only end where nobody sees an edge: under rubber or rail, below the cloth
    inside a pocket, along the cabinet top (under the skirt), or round a Marks quad."""
    q = mid[:2]
    if name == 'Marks':
        return True
    if name == 'Body':
        return abs(mid[2] - (L.p['rail_bottom'] - L.p['skirt_height'])) < 1e-4
    if mid[2] < -0.005:
        return True
    in_play = phys.in_region(q) and phys.clearance(q) > 0.35
    near_hole = any(math.dist(q, c) < r + 0.2 for _, c, r in phys.holes)
    return not in_play or near_hole


