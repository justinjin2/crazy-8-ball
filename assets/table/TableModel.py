class End:
    """One cushion end: a facing, its rail, the fillet, the jaw knob and the heel."""


class Layout:
    def __init__(self, g, p):
        self.g, self.p = g, p
        self.s = g['studs_per_inch']
        self.h = g['cloth']['above_floor_studs']
        self.R = g['ball']['radius']
        self.Rr = g['ball']['render_radius']
        self.nose = g['cushion']['nose_height']
        self.W = g['cushion']['width']
        self.top = g['rail']['top']
        self.rail_w = g['rail']['width']
        self.jaw_r = g['pockets']['jaw_radius']
        self.X0, self.Y0 = g['rail']['outer_half_length'], g['rail']['outer_half_width']
        assert abs(g['cloth']['half_length'] + self.rail_w - self.X0) < 1e-9
        assert abs(g['cloth']['half_width'] + self.rail_w - self.Y0) < 1e-9
        assert p['fillet_radius'] <= self.R
        self.segs = {sg['name']: sg for sg in g['segments']}
        self.pts = {pt['name']: pt for pt in g['points']}
        self.holes = {hl['id']: hl for hl in g['holes']}
        self.cushions = g['cushions']
        self.ends = {}
        for c in self.cushions:
            rail = self.segs[c['rail']]
            for fname in c['facings']:
                self.ends[fname] = self._end(rail, self.segs[fname])
        # Profile levels (setback e behind the nose line, height z above the cloth).
        self.levels = [(p['toe_setback'], p['toe_z']),
                       (p['lower_rounding_setback'], self.nose - p['rounding_dz']),
                       (0.0, self.nose),
                       (p['upper_rounding_setback'], self.nose + p['rounding_dz'])]
        self.nose_level = 2
        self.eU, self.zU = self.levels[-1]
        self.cushion_top = self.top - p['cushion_top_below_rail']
        self.slope = (self.cushion_top - self.zU) / (self.W - self.eU)
        v = [0.0]
        for (e0, z0), (e1, z1) in zip(self.levels, self.levels[1:]):
            v.append(v[-1] + math.hypot(e1 - e0, z1 - z0))
        self.level_v = v
        self.e_bed = p['toe_setback'] + p['bed_under_toe']
        self.pockets = {hid: self._pocket(hl) for hid, hl in self.holes.items()}

    # -- cushion ends ---------------------------------------------------------------------------
    def _end(self, rail, f):
        p = self.p
        e = End()
        e.name, e.rail, e.pocket = f['name'], rail['name'], f['pocket']
        e.N, e.J = tuple(f['a']), tuple(f['b'])
        e.L = length(sub(e.J, e.N))
        e.t = unit(sub(e.J, e.N))
        e.nf = tuple(f['normal'])
        e.of = mul(e.nf, -1)
        e.ra = tuple(rail['a'])
        e.dr = unit(sub(tuple(rail['b']), tuple(rail['a'])))
        e.nr = tuple(rail['normal'])
        e.orr = mul(e.nr, -1)
        e.sigma = 1 if cross(e.t, e.nf) < 0 else -1  # knob traversal: CCW when the throat is on the right
        e.K = e.J
        # Heel: where the nose-level knob circle first crosses the back line (W behind the nose).
        dK = dot(sub(e.K, e.ra), e.orr)
        q = (self.W - dK) / self.jaw_r
        assert -1 < q < 1, ('the knob does not reach the back line', e.name, q)
        base = ang(e.orr)
        alpha0 = ang(sub(self._t2(e, 0.0), e.K))
        best = None
        for cand in (base + math.acos(q), base - math.acos(q)):
            turn = (e.sigma * (cand - alpha0)) % (2 * pi)
            if best is None or turn < best[0]:
                best = (turn, cand)
        e.theta_h = best[1]
        e.P = polar(e.K, self.jaw_r, e.theta_h)
        e.back_point = add(e.ra, mul(e.orr, self.W))  # a point on the back line
        # Fixed vertex counts, from the nose level.
        fc, t1, t2 = self._fillet(e, 0.0)
        span_f = abs(self._short(ang(sub(t1, fc)), ang(sub(t2, fc))))
        e.n_fillet = arc_steps(p['fillet_radius'], span_f, p['chord_tol'])
        span_k = self._knob_span(e, 0.0)
        e.n_knob = arc_steps(self.jaw_r, span_k, p['chord_tol_fine'])
        return e

    @staticmethod
    def _short(a0, a1):
        d = (a1 - a0 + pi) % (2 * pi) - pi
        return d

    def _rk(self, e_off):
        return max(self.jaw_r - e_off, self.p['knob_min_radius'])

    def _fillet(self, e, e_off):
        """Fillet centre and its tangent points on the offset facing and on the knob at level e."""
        rf = self.p['fillet_radius']
        rk = self._rk(e_off)
        rho = rf + e_off
        s_c = e.L - sqrt((rk + rho) ** 2 - rf ** 2)
        fc = add(e.N, add(mul(e.nf, rf), mul(e.t, s_c)))
        t1 = add(e.N, add(mul(e.of, e_off), mul(e.t, s_c)))
        t2 = add(e.K, mul(sub(fc, e.K), rk / (rk + rho)))
        return fc, t1, t2

    def _t2(self, e, e_off):
        return self._fillet(e, e_off)[2]

    def _knob_span(self, e, e_off):
        a = ang(sub(self._t2(e, e_off), e.K))
        return (e.sigma * (e.theta_h - a)) % (2 * pi)

    def end_curve(self, name, e_off):
        """Plan points of one cushion end at setback e_off, from the mitre (nose point) to the heel
        P: [mitre, T1, fillet..., T2, knob..., P]. Same count at every level. Also returns the
        kind of each vertex ('facing', 'fillet', 'knob', 'heel')."""
        e = self.ends[name]
        if e_off == 0.0:
            mitre = e.N
        else:
            mitre = line_intersect(add(e.ra, mul(e.orr, e_off)), e.dr, add(e.N, mul(e.of, e_off)), e.t)
        fc, t1, t2 = self._fillet(e, e_off)
        rf = self.p['fillet_radius'] + e_off
        a0 = ang(sub(t1, fc))
        span_f = self._short(a0, ang(sub(t2, fc)))
        fil = arc(fc, rf, a0, span_f, e.n_fillet)
        rk = self._rk(e_off)
        ak = ang(sub(t2, e.K))
        span_k = e.sigma * self._knob_span(e, e_off)
        knob = arc(e.K, rk, ak, span_k, e.n_knob, equal_error=True)
        pts = [mitre] + fil + knob[1:-1] + [e.P]
        kinds = ['facing'] + ['fillet'] * (len(fil) - 1) + ['knob'] * (len(knob) - 1) + ['heel']
        if e_off == 0.0:
            assert math.dist(knob[-1], e.P) < 1e-9
        return pts, kinds

    def cushion_curve(self, c, e_off):
        f1, f2 = c['facings']
        a, ka = self.end_curve(f1, e_off)
        b, kb = self.end_curve(f2, e_off)
        return list(reversed(a)) + b, list(reversed(ka)) + kb

    def rail_depth(self, c, pt):
        """Distance of a plan point behind a cushion's rail nose line."""
        rail = self.segs[c['rail']]
        return -dot(sub(pt, tuple(rail['a'])), tuple(rail['normal']))

    def top_z(self, c, pt):
        return self.zU + (self.rail_depth(c, pt) - self.eU) * self.slope

    # -- pockets --------------------------------------------------------------------------------
    def _pocket(self, hl):
        p = self.p
        k = hl['kind']
        pk = End()
        pk.id, pk.kind, pk.name = hl['id'], k, hl['name']
        pk.H = (hl['x'], hl['y'])
        pk.r, pk.clear = hl['radius'], hl['clear_radius']
        pk.axis = unit((math.copysign(1, hl['x']), math.copysign(1, hl['y']))) if k == 'corner' \
            else (0.0, math.copysign(1, hl['y']))
        pk.endA, pk.endB = self.ends[hl['facings'][0]], self.ends[hl['facings'][1]]
        pk.Hp = add(pk.H, mul(pk.axis, p['opening_offset'][k]))
        pk.Rc = math.dist(pk.endA.P, pk.Hp)
        assert abs(math.dist(pk.endB.P, pk.Hp) - pk.Rc) < 1e-9, ('opening is not symmetric', pk.id)
        pk.w = p['rim_width'][k]
        pk.cup_r = pk.clear + p['cup_margin']
        # Mouth: counterclockwise from jaws[1] to jaws[2] (legend.holes).
        return pk

    def back_cross(self, pk, end, radius):
        """Where the circle (Hp, radius) crosses this end's back line, on this end's side."""
        roots = line_circle(end.back_point, end.dr, pk.Hp, radius)
        assert roots, ('circle misses the back line', pk.id, radius)
        side = math.copysign(1, cross(pk.axis, sub(end.P, pk.Hp)))
        for s_ in roots:
            q = add(end.back_point, mul(end.dr, s_))
            if math.copysign(1, cross(pk.axis, sub(q, pk.Hp))) == side:
                return q
        raise AssertionError(('no crossing on the heel side', pk.id))

    def far_span(self, pk, a0, a1):
        """Signed turn about Hp from a0 to a1 that passes the far side (the pocket axis)."""
        span = ccw_span(a0, a1)
        through = ccw_span(a0, ang(pk.axis)) < span
        return span if through else span - 2 * pi

    def cup_vertex_angles(self, pk):
        n = self.p['cup_segments']
        a0 = ang(pk.axis)
        return [a0 + 2 * pi * k / n for k in range(n)]

    def cup_radius_vertex(self, pk):
        n = self.p['cup_segments']
        return pk.cup_r * (1 + 1 / cos(pi / n)) / 2

    def cup_point(self, pk, phi):
        """Point on the cup polygon along the ray from the hole centre at angle phi."""
        n = self.p['cup_segments']
        a0 = ang(pk.axis)
        rv = self.cup_radius_vertex(pk)
        k = math.floor(((phi - a0) % (2 * pi)) / (2 * pi / n))
        pa = polar(pk.H, rv, a0 + 2 * pi * k / n)
        pb = polar(pk.H, rv, a0 + 2 * pi * (k + 1) / n)
        return line_intersect(pk.H, (cos(phi), sin(phi)), pa, sub(pb, pa))

    def mouth_span(self, pk, a0, a1):
        """Signed turn about the hole centre from a0 to a1 through the table side."""
        span = ccw_span(a0, a1)
        table = ang(mul(pk.H, -1))
        return span if ccw_span(a0, table) < span else span - 2 * pi

    def casting_limit(self, d):
        """Highest a cap or casting may reach at plan distance d from a hole centre."""
        pk = self.g['pockets']
        w = max(0.0, min(1.0, (pk['casting_reach'] - d) / pk['casting_blend']))
        return self.top + (self.p['casting_top_target'] - self.top) * w


