# name, outward normal of its outer edge, travel axis, start end, finish end. Travel runs
# clockwise seen from above, so the table is on the right. An end is ('mitre', (sx, sy)) at a
# corner or ('seam',) at x = 0 behind a side pocket.
RAIL_PIECES = [
    ('topLeft', (0, 1), (1, 0), ('mitre', (-1, 1)), ('seam',)),
    ('topRight', (0, 1), (1, 0), ('seam',), ('mitre', (1, 1))),
    ('foot', (1, 0), (0, -1), ('mitre', (1, 1)), ('mitre', (1, -1))),
    ('bottomRight', (0, -1), (-1, 0), ('mitre', (1, -1)), ('seam',)),
    ('bottomLeft', (0, -1), (-1, 0), ('seam',), ('mitre', (-1, -1))),
    ('head', (-1, 0), (0, 1), ('mitre', (-1, -1)), ('mitre', (-1, 1))),
]
RAIL_U_OFFSETS = [0.0, 0.17, 0.34, 0.51, 0.68, 0.85]
RAILS_V = {'profile': (0.0, 0.64), 'ends': (0.66, 0.86), 'pearl': (0.87, 0.94), 'hidden': (0.95, 1.0)}


def corner_pocket(L, corner):
    for pk in L.pockets.values():
        if pk.kind == 'corner' and math.copysign(1, pk.H[0]) == corner[0] and math.copysign(1, pk.H[1]) == corner[1]:
            return pk
    raise AssertionError(corner)


def side_pocket(L, sy):
    for pk in L.pockets.values():
        if pk.kind == 'side' and math.copysign(1, pk.H[1]) == sy:
            return pk
    raise AssertionError(sy)


def piece_pocket(L, outward, end):
    if end[0] == 'mitre':
        return corner_pocket(L, end[1])
    return side_pocket(L, outward[1])


def outer_depth(L, outward):
    return L.X0 if outward[0] else L.Y0


def ring_points(L, outward, axis, ends, e):
    """The outer boundary offset e inward, for one piece in travel order: [(point, kind)], where
    kind is 'mid' (facet midpoint on the mitre), 'facet' (facet meets the straight edge),
    'seam', 'chamfer' or 'edge'."""
    p = L.p
    D = outer_depth(L, outward) - e
    edge_pt = mul(outward, D)
    out = []
    for which, end in enumerate(ends):
        if end[0] == 'mitre':
            sx, sy = end[1]
            pk = corner_pocket(L, end[1])
            fsum = L.X0 + L.Y0 - p['corner_clip'] - e * sqrt(2)
            # facet line: sx x + sy y = fsum, direction (-sy, sx) along it
            fp = (sx * fsum / 2, sy * fsum / 2)
            fd = unit((-sy, sx))
            mid = line_intersect(fp, fd, pk.H, unit((sx, sy)))
            meet = line_intersect(fp, fd, edge_pt, axis)
            pair = [(mid, 'mid'), (meet, 'facet')]
        else:
            seam = line_intersect(edge_pt, axis, (0.0, 0.0), (0.0, 1.0))
            direction = 1 if which == 0 else -1
            cham = add(seam, mul(axis, direction * p['seam_chamfer']))
            pair = [(seam, 'seam'), (cham, 'chamfer')]
        out += pair if which == 0 else list(reversed(pair))
    return out


def rim_outer(L, pk):
    """The rim-outer circle (the rail's pocket cut) from F_A round the far side to F_B, as
    [(point, kind)]: one sampling shared by the rail pieces and the leather rim, so they meet
    vertex to vertex. Kinds: 'edge', 'mid' (on the pocket axis) or 'seam'/'chamfer' (x = 0 / 0.03)."""
    if getattr(pk, 'rim_outer_pts', None) is not None:
        return pk.rim_outer_pts
    p = L.p
    rho = pk.Rc + pk.w
    fa = L.back_cross(pk, pk.endA, rho)
    fb = L.back_cross(pk, pk.endB, rho)
    a_axis = ang(pk.axis)
    keys = [(ang(sub(fa, pk.Hp)), fa, 'edge')]
    if pk.kind == 'side':
        for sx in (-1, 1):
            xc = sx * p['seam_chamfer']
            dy = sqrt(rho * rho - (xc - pk.Hp[0]) ** 2)
            q = (xc, pk.Hp[1] + math.copysign(dy, pk.axis[1]))
            keys.append((ang(sub(q, pk.Hp)), q, 'chamfer'))
        keys.append((a_axis, add(pk.Hp, mul(pk.axis, rho)), 'seam'))
    else:
        keys.append((a_axis, add(pk.Hp, mul(pk.axis, rho)), 'mid'))
    keys.append((ang(sub(fb, pk.Hp)), fb, 'edge'))
    a0 = keys[0][0]
    sgn = math.copysign(1, L.far_span(pk, a0, keys[-1][0]))
    keys.sort(key=lambda k: ((k[0] - a0) * sgn) % (2 * pi))
    out = [(keys[0][1], keys[0][2])]
    for (ka, _, _), (kb, qb, kind) in zip(keys, keys[1:]):
        span = ((kb - ka) * sgn) % (2 * pi) * sgn
        n = arc_steps(rho, span, p['chord_tol'])
        out += [(q, 'edge') for q in arc(pk.Hp, rho, ka, span, n)[1:-1]]
        out.append((qb, kind))
    pk.rim_outer_pts = out
    return out


def inner_chain(L, name, outward, axis, ends):
    """Rail inner edge at the flat top, in travel order: rim-outer arc of the start pocket, the
    cushion back line, rim-outer arc of the finish pocket. Kinds as ring_points."""
    p = L.p
    chains = []
    for which, end in enumerate(ends):
        pk = piece_pocket(L, outward, end)
        cushion_end = pk.endA if pk.endA.rail == name else pk.endB
        assert cushion_end.rail == name, (name, pk.id)
        pts = rim_outer(L, pk)
        k_axis = [k for _, k in pts].index('mid' if end[0] == 'mitre' else 'seam')
        half = list(reversed(pts[:k_axis + 1])) if cushion_end is pk.endA else pts[k_axis:]
        # a seam end keeps only its own chamfer point (x on this piece's side)
        if end[0] == 'seam':
            direction = 1 if which == 0 else -1
            want_x = direction * p['seam_chamfer'] * axis[0]
            half = [(q, k) for q, k in half if k != 'chamfer' or abs(q[0] - want_x) < 1e-9]
        chains.append(half)
    return chains[0] + list(reversed(chains[1]))


def bullnose_profile(L):
    """(e, z, phi) from the flat band edge (e = bullnose width) down to the outer face top."""
    p = L.p
    bw = L.rail_w - p['rail_band_to']
    bh = p['bullnose_height']
    n = arc_steps(max(bw, bh), pi / 2, p['chord_tol'])
    out = []
    for k in range(n + 1):
        phi = pi / 2 * (1 - k / n)
        out.append((bw * (1 - cos(phi)), L.top - bh + bh * sin(phi), phi))
    return out, bw, bh


def chamfer_offset(phi, bw, bh, c):
    """Displacement (de, dz) into the wood, c deep, at bullnose parameter phi."""
    nx, nz = -cos(phi) / bw, sin(phi) / bh
    n = math.hypot(nx, nz)
    return (-nx / n * c, -nz / n * c)


def build_rail_piece(L, part, index, piece):
    p = L.p
    name, outward, axis, start, finish = piece
    ends = (start, finish)
    kr = p['rails_px_per_stud'] / p['atlas_px'] * L.s
    u_off = RAIL_U_OFFSETS[index]
    prof, bw, bh = bullnose_profile(L)
    arcs = [0.0]
    for a, b in zip(prof, prof[1:]):
        arcs.append(arcs[-1] + math.hypot(b[0] - a[0], b[1] - a[1]))
    V1 = 5.5
    v0p, v1p = RAILS_V['profile']
    D = outer_depth(L, outward)
    c = p['seam_chamfer']
    zb = p['rail_bottom']
    inward = mul(outward, -1)

    def e_edge(pt):
        return D - dot(pt, outward)

    seam_dir = -1.0 if ends[0][0] == 'seam' else 1.0

    def u_axis(pt, kind=None, phi=pi / 2):
        """u along the grain; a seam vertex sits one chamfer slope further out so the chamfer
        keeps its texel density."""
        d = c * cos(phi)
        extra = (sqrt(c * c + d * d) - c) * seam_dir if kind == 'seam' else 0.0
        return u_off + (dot(pt, axis) + extra) * kr

    rings = [ring_points(L, outward, axis, ends, e) for e, _, _ in prof]
    kinds = [k for _, k in rings[0]]
    nr = len(kinds)

    def disp(pt, kind, phi, z):
        if kind != 'seam':
            return (pt[0], pt[1], z)
        # the seam V fades out over the bullnose: full on the outer face, none on the flat band
        de, dz = chamfer_offset(phi, bw, bh, c * cos(phi))
        q = add(pt, mul(inward, de))
        return (q[0], q[1], z + dz)

    ring_ids = []
    for (e, z, phi), ring in zip(prof, rings):
        ring_ids.append([part.vk(disp(pt, kind, phi, z)) for pt, kind in ring])
    # bottom of the outer face
    bottom_ids = [part.vk(disp(pt, kind, 0.0, zb)) for pt, kind in rings[-1]]
    chain = inner_chain(L, name, outward, axis, ends)
    top_ids = [part.vk((q[0], q[1], L.top)) for q, k in chain]
    low_ids = [part.vk((q[0], q[1], zb)) for q, k in chain]

    def facet_u(pt, j):
        """Grain along the facet, running with the travel: distance from the mitre diagonal."""
        first = j < nr // 2
        end = ends[0] if first else ends[1]
        mid_pt = rings[0][0][0] if first else rings[0][-1][0]
        meet_pt = rings[0][1][0] if first else rings[0][-2][0]
        fd = unit(sub(meet_pt, mid_pt)) if first else unit(sub(mid_pt, meet_pt))
        pk = corner_pocket(L, end[1])
        return u_off + 0.45 + dot(sub(pt, pk.H), fd) * kr

    start_faces = len(part.faces)
    # Bullnose loft and outer face (strip 1)
    for k in range(len(prof) - 1):
        for j in range(nr - 1):
            facet = {kinds[j], kinds[j + 1]} == {'mid', 'facet'}
            pa, pb = rings[k][j][0], rings[k][j + 1][0]
            qa, qb = rings[k + 1][j][0], rings[k + 1][j + 1][0]
            if facet:
                us = [facet_u(pa, j), facet_u(pb, j), facet_u(qb, j), facet_u(qa, j)]
            else:
                pk_, pk1 = prof[k][2], prof[k + 1][2]
                us = [u_axis(pa, kinds[j], pk_), u_axis(pb, kinds[j + 1], pk_), u_axis(qb, kinds[j + 1], pk1),
                      u_axis(qa, kinds[j], pk1)]
            va, vb = v0p + (V1 + arcs[k]) * kr, v0p + (V1 + arcs[k + 1]) * kr
            part.quad(ring_ids[k][j], ring_ids[k][j + 1], ring_ids[k + 1][j + 1], ring_ids[k + 1][j],
                      [(us[0], va), (us[1], va), (us[2], vb), (us[3], vb)], T_RAIL_BULL)
    zo = prof[-1][1]
    for j in range(nr - 1):
        facet = {kinds[j], kinds[j + 1]} == {'mid', 'facet'}
        pa, pb = rings[-1][j][0], rings[-1][j + 1][0]
        us = [facet_u(pa, j), facet_u(pb, j)] if facet else [u_axis(pa, kinds[j], 0.0), u_axis(pb, kinds[j + 1], 0.0)]
        va, vb = v0p + (V1 + arcs[-1]) * kr, v0p + (V1 + arcs[-1] + zo - zb) * kr
        part.quad(ring_ids[-1][j], ring_ids[-1][j + 1], bottom_ids[j + 1], bottom_ids[j],
                  [(us[0], va), (us[1], va), (us[1], vb), (us[0], vb)], T_RAIL_OUTER)
    # Flat band with the sights as holes (their own faces)
    ring_top = rings[0]
    outer_loop = [q for q, _ in chain] + [q for q, _ in reversed(ring_top)]
    loop_kinds = [None] * len(chain) + [k for _, k in reversed(ring_top)]
    outer_ids = top_ids + list(reversed(ring_ids[0]))
    holes, hole_meta = [], []
    for centre, across in sight_positions(L, name):
        along = (-across[1], across[0])
        hl, hw = p['sight_length'] / 2, p['sight_width'] / 2
        pts = [add(centre, mul(across, -hl)), add(centre, mul(along, -hw)), add(centre, mul(across, hl)),
               add(centre, mul(along, hw))]
        holes.append(pts)
        hole_meta.append((centre, across, along))
    extra = []
    n_chain = len(chain)
    for a_i, (_, k) in enumerate(chain):
        if k == 'chamfer':
            # matching ring chamfer point: first or last ring vertex pair
            r_i = 1 if a_i < n_chain // 2 else nr - 2
            extra.append((a_i, n_chain + (nr - 1 - r_i)))
    verts, tris = tc.triangulate(outer_loop, holes, extra)
    hole_ids = []
    for hpts in holes:
        hole_ids += [part.vk((q[0], q[1], L.top)) for q in hpts]
    all_ids = outer_ids + hole_ids
    for tri in tris:
        uvs = [(u_axis(verts[i], loop_kinds[i] if i < len(loop_kinds) else None),
                v0p + (V1 - (e_edge(verts[i]) - bw)) * kr) for i in tri]
        part.f([all_ids[i] for i in tri], uvs, T_RAIL_FLAT)
    p0, p1 = RAILS_V['pearl']
    for h_i, (centre, across, along) in enumerate(hole_meta):
        ids = hole_ids[4 * h_i:4 * h_i + 4]
        pts = holes[h_i]
        uvs = [(0.02 + h_i * 0.05 + (0.25 - dot(sub(q, centre), along)) * kr,
                p0 + (dot(sub(q, centre), across) + 0.55) * kr) for q in pts]
        if cross(sub(pts[1], pts[0]), sub(pts[2], pts[0])) < 0:
            ids, uvs = list(reversed(ids)), list(reversed(uvs))
        part.f(ids, uvs, T_SIGHT)
    # Bottom (hidden)
    h0, h1 = RAILS_V['hidden']
    hs = kr * p['hidden_uv_scale']
    bottom_loop = [q for q, _ in chain] + [q for q, _ in reversed(rings[-1])]
    bottom_plan = []
    for q, k in reversed(rings[-1]):
        bottom_plan.append(q)
    bl_ids = low_ids + list(reversed(bottom_ids))
    bl_pts = [q for q, _ in chain] + [(part.co[i][0], part.co[i][1]) for i in reversed(bottom_ids)]
    verts, tris = tc.triangulate(bl_pts)
    for tri in tris:
        part.f([bl_ids[i] for i in reversed(tri)],
               [(u_off - verts[i][0] * hs, h0 + 0.025 + verts[i][1] * hs * 0.1) for i in reversed(tri)],
               T_RAIL_BOTTOM)
    # Inner face (hidden but for 0.02 above the cushion)
    s_chain = [0.0]
    for j in range(n_chain - 1):
        s_chain.append(s_chain[-1] + math.dist(chain[j][0], chain[j + 1][0]))
    for j in range(n_chain - 1):
        ua, ub = u_off + s_chain[j] * kr, u_off + s_chain[j + 1] * kr
        part.quad(top_ids[j + 1], top_ids[j], low_ids[j], low_ids[j + 1],
                  [(ub, h1), (ua, h1), (ua, h0), (ub, h0)], T_RAIL_INNER)
    # End faces
    e0, e1 = RAILS_V['ends']
    for which in (0, 1):
        j_ring = 0 if which == 0 else nr - 1
        j_chain = 0 if which == 0 else n_chain - 1
        ids = [top_ids[j_chain]] + [ring_ids[k][j_ring] for k in range(len(prof))] + \
            [bottom_ids[j_ring], low_ids[j_chain]]
        base = part.co[low_ids[j_chain]]
        uvs = []
        for i in ids:
            q = part.co[i]
            hdist = math.hypot(q[0] - base[0], q[1] - base[1]) * kr
            uvs.append((0.05 + hdist if which == 1 else 0.5 - hdist, e0 + (q[2] - zb) * kr))
        if which == 1:
            ids, uvs = list(reversed(ids)), list(reversed(uvs))
        part.f(ids, uvs, T_RAIL_END)
    part.orient_closed()
    return part


def sight_positions(L, name):
    """(centre, across) for the three diamonds on a rail piece; across points away from the table."""
    p = L.p
    d = p['sight_from_nose']
    sp = p['sight_spacing']
    hl, hw = L.g['cloth']['half_length'], L.g['cloth']['half_width']
    out = []
    if name in ('topLeft', 'topRight', 'bottomLeft', 'bottomRight'):
        sy = 1 if name.startswith('top') else -1
        sx = -1 if name.endswith('Left') else 1
        for k in (1, 2, 3):
            out.append(((sx * k * sp, sy * (hw + d)), (0.0, float(sy))))
    else:
        sx = 1 if name == 'foot' else -1
        for yk in (-1, 0, 1):
            out.append(((sx * (hl + d), yk * sp), (float(sx), 0.0)))
    return out


