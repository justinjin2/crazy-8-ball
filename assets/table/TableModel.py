class Physics:
    """The game's 2D contact model, straight from Geometry.json."""

    def __init__(self, L):
        self.L = L
        g = L.g
        self.segments = [(sg['name'], tuple(sg['a']), tuple(sg['b'])) for sg in g['segments']]
        self.points = [(pt['name'], (pt['x'], pt['y']), pt['radius']) for pt in g['points']]
        self.holes = [(hl['id'], (hl['x'], hl['y']), hl['radius']) for hl in g['holes']]
        self.throats = []
        for pk in L.pockets.values():
            ja, jb = pk.endA.J, pk.endB.J
            a0 = ang(sub(ja, pk.H))
            span = L.mouth_span(pk, a0, ang(sub(jb, pk.H)))
            arcp = [polar(pk.H, pk.r, a0 + span * k / 24) for k in range(25)]
            self.throats.append([pk.endA.N, ja] + arcp + [jb, pk.endB.N])
        self.hl = g['cloth']['half_length']
        self.hw = g['cloth']['half_width']

    def clearance(self, q):
        """Least (distance - contact radius) to the physics boundary: >= R means a legal centre."""
        best = 1e9
        for _, a, b in self.segments:
            best = min(best, tc.seg_dist(q, a, b))
        for _, c, r in self.points:
            best = min(best, math.dist(q, c) - r)
        return best

    def in_region(self, q):
        if abs(q[0]) <= self.hl and abs(q[1]) <= self.hw:
            return True
        return any(tc.point_in_poly(q, t) for t in self.throats)

    def captured(self, q):
        return any(math.dist(q, c) < r for _, c, r in self.holes)

    def free(self, q, radius):
        return self.in_region(q) and not self.captured(q) and self.clearance(q) >= radius - 1e-9

    def near_band(self, q, band):
        return self.clearance(q) <= band or any(math.dist(q, c) <= r + band for _, c, r in self.holes)


class MeshData:
    def __init__(self, obj, tags, L):
        s, h = L.s, L.h
        me = obj.data
        self.name = obj.name
        self.co = [(v.co.x / s, v.co.y / s, (v.co.z - h) / s) for v in me.vertices]
        self.polys = [tuple(pl.vertices) for pl in me.polygons]
        self.loops = [tuple(pl.loop_indices) for pl in me.polygons]
        self.uv = [tuple(d.uv) for d in me.uv_layers[0].data]
        self.tags = tags

    def select(self, tagset=None, exclude=None):
        out = []
        for poly, t in zip(self.polys, self.tags):
            if tagset is not None and t not in tagset:
                continue
            if exclude is not None and t in exclude:
                continue
            out.append(poly)
        return out


def bvh_of(meshes, tagset=None, exclude=None):
    co, polys, tags = [], [], []
    for md in meshes:
        base = len(co)
        co += md.co
        for pl, t in zip(md.polys, md.tags):
            if (tagset is not None and t not in tagset) or (exclude is not None and t in exclude):
                continue
            polys.append(tuple(i + base for i in pl))
            tags.append((md.name, t))
    return BVHTree.FromPolygons(co, polys, all_triangles=True), co, tags


def frange(a, b, step):
    n = int(math.floor((b - a) / step + 1e-9))
    return [a + step * k for k in range(n + 1)]


def tri_area3(a, b, c):
    ab = (b[0] - a[0], b[1] - a[1], b[2] - a[2])
    ac = (c[0] - a[0], c[1] - a[1], c[2] - a[2])
    cr = vcross(ab, ac)
    return 0.5 * math.sqrt(cr[0] ** 2 + cr[1] ** 2 + cr[2] ** 2), cr


def fit_circle(pts):
    """Algebraic least-squares circle: (centre, radius)."""
    n = len(pts)
    sx = sum(q[0] for q in pts) / n
    sy = sum(q[1] for q in pts) / n
    u = [q[0] - sx for q in pts]
    v = [q[1] - sy for q in pts]
    suu = sum(a * a for a in u)
    svv = sum(b * b for b in v)
    suv = sum(a * b for a, b in zip(u, v))
    suuu = sum(a ** 3 for a in u)
    svvv = sum(b ** 3 for b in v)
    suvv = sum(a * b * b for a, b in zip(u, v))
    svuu = sum(b * a * a for a, b in zip(u, v))
    det = suu * svv - suv * suv
    uc = (0.5 * (suuu + suvv) * svv - 0.5 * (svvv + svuu) * suv) / det
    vc = (0.5 * (svvv + svuu) * suu - 0.5 * (suuu + suvv) * suv) / det
    r = math.sqrt(uc * uc + vc * vc + (suu + svv) / n)
    return (uc + sx, vc + sy), r


